-- 92: бот, который отвечает заранее заданными ответами (v1.344.0).
--
-- Зачем. До этого «свой бот» означал: напиши программу, подними её на своём
-- https-адресе, настрой вебхук. Человеку, который просто хочет, чтобы по
-- команде /правила бот прислал правила сервера, это недоступно вовсе — а
-- хотят этого чаще всего.
--
-- Такой бот — тоже встроенный (builtin = 'simple'): его выполняет наша же
-- функция bot-interact, никакого «снаружи» у него нет. Отличие от готовых
-- ботов «от нас» в том, что ответы у него не зашиты в код, а лежат здесь —
-- их пишет владелец.
alter table public.bot_commands add column if not exists reply text;

-- Ответ виден всем, кто видит команды бота: их и так читает любой участник
-- сервера, чтобы работало автодополнение «/». Отдельного правила не нужно —
-- bc_read из 50_bots.sql уже пускает на чтение всех вошедших.

-- Ограничение длины — на стороне базы, а не только в форме: ответ уходит
-- прямо в сообщение, и клиент тут не единственный вход.
alter table public.bot_commands drop constraint if exists bot_commands_reply_len;
alter table public.bot_commands add constraint bot_commands_reply_len
  check (reply is null or length(reply) <= 2000);
