-- v1.378.0: находки сплошного разбора на уязвимости.
--
-- ── A) Обложки игр: заполнять можно, переписывать чужое — нет ──────────────
--
-- game_covers — общий кэш на всех: игра ищется во внешнем сервисе один раз, и
-- результат кладётся сюда любым вошедшим. Это осознанно. Но правило разрешало и
-- ПЕРЕПИСЫВАТЬ уже найденное: кто угодно мог подменить обложку «Counter-Strike 2»
-- на что захочет, и её увидели бы все. Адрес ограничен https (миграция 87), то
-- есть подставить скрипт нельзя — а вот картинку-подмену или счётчик посещений,
-- который соберёт адреса всех, кто её увидит, вполне.
--
-- Кэш заполняют, а не переписывают. Разрешаем правку только там, где полезного
-- значения ещё нет: пустая обложка или отметка «не нашли» — их перепроверять надо.
drop policy if exists "game_covers update" on public.game_covers;
create policy "game_covers update" on public.game_covers
  for update to authenticated
  using (cover_url is null or status = 'not_found')
  with check (cover_url is null or cover_url like 'https://%');

-- Удаления не было и не нужно: строку кэша незачем убирать, а разрешение на это
-- дало бы обход запрета выше — удалил и вставил заново с чем угодно.
drop policy if exists "game_covers delete" on public.game_covers;
