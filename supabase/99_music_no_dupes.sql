-- v1.373.0: один и тот же трек — один раз.
--
-- Что было не так. Проверка «уже есть» стояла в интерфейсе и только на двух из
-- четырёх путей добавления: при импорте плейлиста и при сохранении одиночной
-- ссылки. Файл, залитый с компьютера, и трек, добавленный вторым человеком
-- одновременно, проходили мимо неё. А трекотека общая — значит и дубликаты
-- видели все.
--
-- Проверять это должна база: интерфейсов у одной таблицы много (два окна плеера,
-- импорт плейлиста, загрузка файлов), а таблица одна. К тому же между «посмотрел,
-- нет ли такого» и «вставил» проходит время, и в этот зазор помещается вторая
-- вставка с другого устройства — от этого никакая проверка в интерфейсе не спасает.
--
-- Сначала убираем то, что уже накопилось, иначе уникальный указатель не создастся.

-- 1) Оставляем самую раннюю запись каждого адреса, остальные убираем.
--    Именно раннюю: у неё больше шансов иметь дозаписанные обложку и длительность.
delete from music_tracks a
using music_tracks b
where a.url = b.url
  and (a.created_at > b.created_at
       or (a.created_at = b.created_at and a.id > b.id));

-- 2) Дальше повторов не будет. Указатель, а не ограничение: по нему же ускорится
--    и проверка «есть ли такой трек» при добавлении.
drop index if exists music_tracks_url_uniq;
create unique index music_tracks_url_uniq on music_tracks (url);
