-- 77: владелец не может покинуть собственный сервер (v1.314.0).
--
-- Что было. В интерфейсе пункт «Покинуть сервер» владельцу не показывался, и
-- функция выхода дополнительно проверяла владельца у себя. Но правило доступа к
-- базе разрешало удалить свою запись об участии КОМУ УГОДНО, включая владельца:
--
--   create policy "sm_delete" on server_members for delete using (user_id = auth.uid());
--
-- То есть запрет держался только на клиенте. Любой изменённый клиент, случайный
-- сбой или прямой запрос оставили бы сервер без владельца: настройки, удаление и
-- передача прав завязаны на owner, и восстановить его было бы уже нечем.
--
-- Как в Discord: владелец сначала передаёт права или удаляет сервер, и только
-- потом может уйти. Правило ниже выражает ровно это, а не прячет кнопку.
--
-- Исключение участников не затрагивается: оно идёт через функцию kick_member
-- (34_permissions.sql, обновлена в 68_audit_log.sql), которая работает с правами
-- определившего её и этому правилу не подчиняется.

drop policy if exists "sm_delete" on public.server_members;
create policy "sm_delete" on public.server_members
  for delete to authenticated using (
    user_id = auth.uid()
    -- Владелец своего сервера уйти не может: пусть сначала передаст права или удалит сервер.
    and not exists (
      select 1 from public.servers s
      where s.id = server_members.server_id and s.owner = auth.uid()
    )
  );
