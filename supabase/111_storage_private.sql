-- 111: закрыть бакет вложений (v1.557.0, находка F1 аудита, последний шаг)
--
-- ⚠️ ПРИМЕНЯТЬ НЕ СРАЗУ. Это единственная миграция в проекте, которую нельзя
-- выполнить в тот же день, когда она появилась. Ниже написано почему и когда.
--
-- ЧТО ОНА ДЕЛАЕТ. Снимает с бакетов признак «публичный». После этого адрес вида
--     /storage/v1/object/public/attachments/<uid>/<время>_<имя файла>
-- перестаёт отдавать файл кому угодно без входа. Останутся работать подписанные
-- ссылки — те, что приложение получает через createSignedUrl и по которым с
-- v1.557.0 показывает все вложения (src/lib/attachUrl.ts).
--
-- ПОЧЕМУ НЕ СЕГОДНЯ. У людей на руках старые версии приложения. Они показывают
-- вложения по постоянному публичному адресу и подписывать ничего не умеют. Для
-- них закрытый бакет означает, что ВСЯ история переписки разом станет битыми
-- картинками — не только новые сообщения, а всё, что когда-либо отправлялось.
--
-- КОГДА МОЖНО. Когда обновление 1.557.0 (или новее) разошлось: Windows
-- обновляется само, Android — само, веб-версия обновляется при перезагрузке
-- страницы. Разумный срок — неделя-две после выпуска. Проверить можно грубо:
-- если жалоб на «не открывается картинка» нет, а версия в выпуске давно новая,
-- значит разошлось.
--
-- КАК ПРОВЕРИТЬ, ЧТО СРАБОТАЛО. После применения:
--   1. Открыть в приложении переписку со старой картинкой — она обязана
--      показаться (приложение подпишет ссылку само).
--   2. Скопировать «Ссылку на медиа», открыть её в браузере БЕЗ входа в Ponoi —
--      обязан прийти отказ, а не файл. До миграции приходит файл.
-- Второй пункт и есть смысл всей находки F1.
--
-- ЕСЛИ ЧТО-ТО ПОШЛО НЕ ТАК — откат в одну строку, внизу файла.
--
-- ЧЕГО ЭТА МИГРАЦИЯ ВСЁ РАВНО НЕ ДАЁТ. Подписать ссылку может ЛЮБОЙ вошедший
-- (правило чтения из миграции 110 — `to authenticated`), если знает путь. Путь
-- содержит идентификатор отправителя и настоящее имя файла, то есть угадать его
-- трудно, но это не право доступа. Настоящая защита вложения — шифрование
-- («Шифровать вложения» в настройках приватности): после него хранилище
-- перестаёт быть доверенным звеном вовсе. Так и написано на /security/.

-- ── Закрыть бакеты ──────────────────────────────────────────────────────────
update storage.buckets set public = false where id in ('attachments', 'modfiles');

-- Аватары НЕ закрываем. Они показываются десятками в каждом списке, меняются
-- редко и хорошо кэшируются браузером; подписывать их означало бы сотни
-- подписей на один экран ради пути, в котором нет ничего, кроме идентификатора
-- владельца — а он и так виден рядом с аватаркой. Это решение записано в
-- SECURITY_ARCHITECTURE_AUDIT.md и на странице /security/, а не умолчано.

