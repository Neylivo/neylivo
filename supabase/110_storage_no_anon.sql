-- 110: закрываем перечисление хранилища вложений и аватаров (v1.557.0)
--
-- ЧТО НЕ ТАК. В 04_storage.sql правила чтения написаны так:
--     create policy "attach_read" on storage.objects for select
--       using ( bucket_id = 'attachments' );
-- Без "to authenticated". Значит правило совпадает и для роли anon — той самой,
-- чей ключ лежит в собранном веб-приложении и виден каждому, кто откроет
-- исходник страницы.
--
-- Последствие проверено на рабочем проекте: с этим публичным ключом
-- перечисляется весь бакет. Папки в нём — идентификаторы пользователей, внутри
-- каждой файлы этого человека с настоящими именами. То есть выгрузить вложения
-- ВСЕХ пользователей может кто угодно, не заходя в приложение.
--
-- ЧТО ДЕЛАЕТ ЭТА МИГРАЦИЯ. Требует вход, чтобы перечислить содержимое бакета.
-- После неё выгрузка «всего разом» посторонним закрыта.
--
-- ЧЕГО ОНА НЕ ДЕЛАЕТ, И ЭТО ВАЖНО ПОНИМАТЬ. Бакеты остаются ПУБЛИЧНЫМИ: прямая
-- ссылка вида /storage/v1/object/public/attachments/... по-прежнему отдаёт файл
-- без всякого входа. Так и задумано на этом шаге — тысячи таких ссылок лежат
-- внутри старых сообщений (messages.attach_url, dm_messages.attach_url), и
-- закрой мы бакет сейчас, вся история переписки осыпалась бы битыми картинками.
--
-- Полное исправление идёт по шагам, и они описаны в
-- SECURITY_ARCHITECTURE_AUDIT.md (находка F1):
--   1) эта миграция — перечисление закрыто, ничего не сломано;
--   2) выдача через createSignedUrl вместо getPublicUrl в src/lib/storage.ts;
--   3) перенос старых записей: в базе вместо готового адреса хранится путь;
--   4) только после этого бакет становится приватным;
--   5) шифрование вложений включается по умолчанию — после чего хранилище
--      перестаёт быть доверенным звеном вовсе.
--
-- До шага 5 единственная настоящая защита вложения — переключатель «шифровать
-- вложения» в настройках приватности. Он есть и он работает.
--
-- Применять один раз в Supabase → SQL Editor.

-- ── attachments ─────────────────────────────────────────────────────────────
drop policy if exists "attach_read" on storage.objects;
create policy "attach_read" on storage.objects for select to authenticated
  using ( bucket_id = 'attachments' );

-- ── avatars ─────────────────────────────────────────────────────────────────
-- Тот же изъян и та же причина: по списку аватаров видно всех пользователей.
drop policy if exists "avatars_read" on storage.objects;
create policy "avatars_read" on storage.objects for select to authenticated
  using ( bucket_id = 'avatars' );

-- ── modfiles ────────────────────────────────────────────────────────────────
-- Здесь путь — это хеш содержимого, и личного в нём нет. Но перечисление всё
-- равно ни к чему: по списку видно, кто какие сборки собирает.
drop policy if exists "modfiles_read" on storage.objects;
create policy "modfiles_read" on storage.objects for select to authenticated
  using ( bucket_id = 'modfiles' );
