// v1.377.0: очередь под человека, а не случайный набор.
//
// Что было. «Дальше» шло просто по порядку склада — то есть по времени, когда
// трек кто-то добавил. К самому человеку это не имело отношения никакого: он
// слушает пять песен, а очередь предлагает то, что позавчера выложил сосед.
//
// v1.399.0: очередь стала рекомендацией, а не только счётчиком прослушиваний.
//
// Считать «сколько раз слушал» — это про человека вообще, а не про то, что
// играет сейчас. После спокойной песни такой список с одинаковой охотой
// предложит и её продолжение, и что-нибудь совершенно постороннее, просто
// потому, что оно чаще игралось. Поэтому теперь у подбора несколько сигналов, и
// главный из них — похоже ли предлагаемое на то, что человек слушает прямо
// сейчас:
//
//   • тот же исполнитель — самый сильный сигнал: чаще всего дальше хотят именно
//     его же;
//   • похожее название — общие значимые слова: части одной вещи, ремиксы, живые
//     версии; слабее автора, потому что совпадение бывает случайным;
//   • давно ли слушал сам — чем дольше песня отдыхала, тем охотнее она снова
//     звучит (до v1.435.0 тут было обратное — «сколько раз слушал», см. ниже);
//   • сколько раз слушают все — помогает, когда про человека ещё ничего не
//     известно (новый аккаунт, пустая история);
//   • только что игравшее — наоборот, отодвигается: крутить по кругу одно и то
//     же очередь не должна;
//   • незнакомое — подмешивается намеренно. Без этого очередь схлопывается в
//     бесконечное повторение любимой пятёрки, и нового человек не услышит
//     никогда.
//
// Числа подобраны так, чтобы ни один сигнал не был решающим в одиночку: один
// общий исполнитель не перевешивает сотню прослушиваний, а сотня прослушиваний
// не перекрывает совсем свежий трек того же автора. Порядок склада остаётся
// последним разрешителем ничьих — от него выдача устойчива и не «прыгает» при
// каждом пересчёте.
//
// v1.424.0: это стало ВОЛНОЙ, а не «лучшим по очкам».
//
// Что было не так, и это ловилось руками за минуту. У исполнителя три песни —
// и очередь гоняла ровно их: «тот же исполнитель» давал +100, а отодвигание
// только что игравшего было мягким, всего до −120, и на четвёртом шаге первая
// песня снова оказывалась лучшей. Человек слушал три трека по кругу сто раз,
// хотя в складе лежали сотни других.
//
// Как это работает в «волне» (и в любом радио):
//
//   1. ЗАПРЕТ ПОВТОРА. Только что игравшее не «слабее», а НЕЛЬЗЯ, пока не
//      пройдёт достаточно других треков. Окно зависит от размера склада: на
//      трёх треках повторяться придётся, на большом — не раньше двадцати
//      других. Мягкий минус тут не работает в принципе: любое достаточно
//      большое сходство его перекроет.
//   2. НЕ БОЛЬШЕ ДВУХ ПОДРЯД ОДНОГО ИСПОЛНИТЕЛЯ. Два — это приятно, третий
//      подряд — это уже «зациклило». После двух подряд его же следующая песня
//      уходит вниз, и волна переходит к другому автору.
//   3. ОСТАЛЬНОЕ: похожесть, давность своего прослушивания, общие
//      прослушивания слабым фоном и незнакомое.
//
// v1.435.0: СИГНАЛ «ТЫ ЭТО ЧАСТО СЛУШАЕШЬ» УБРАН СОВСЕМ — по прямой просьбе
// владельца, и она справедлива. Он делал обратное тому, зачем очередь нужна:
// чем чаще песня уже звучала, тем охотнее её ставили снова. На складе в восемь
// тысяч треков волна из-за этого ходила по одной и той же сотне, а остальное
// человек не слышал никогда. Вместо частоты теперь давность и незнакомое.
//
// Запреты сделаны большими отрицательными числами, а не выбрасыванием из
// списка: если весь склад окажется под запретом (три трека всего), волна всё
// равно выберет самое давнее, а не остановится.

import { songKey } from './songKey'

export interface QueueTrack {
  id: string
  /** Название — по нему ищется сходство. Без него сигнал просто не работает. */
  name?: string
  /** Исполнитель, если известен. */
  author?: string
  /** Сколько раз трек слушали все вместе. */
  plays?: number
}

export interface PersonalInput<T extends QueueTrack> {
  /** Весь склад в его обычном порядке. */
  tracks: T[]
  /** Номер того, что играет сейчас. */
  idx: number
  /** Сколько раз я слушал каждый трек. */
  plays: Record<string, number>
  /**
   * Когда слушал в последний раз (мс).
   *
   * v1.435.0: это уже не только разрешение ничьих. По давности считается
   * основной сигнал вместо прежнего «часто слушаешь» (см. recommend).
   */
  lastAt?: Record<string, number>
  /** Сейчас (мс) — снаружи, чтобы давность проверялась. */
  now?: number
  /** Что играло только что, от свежего к старому: это отодвигается назад. */
  recent?: string[]
  /**
   * Сколько незнакомого подмешать.
   *
   * v1.435.0: больше не используется — незнакомое теперь не «подмешивается»
   * тремя штуками от начала склада, а имеет полноценный вес у КАЖДОГО трека,
   * которого человек не слышал. Поле оставлено, чтобы не ломать вызовы.
   */
  freshCount?: number
  /**
   * Сколько треков должно пройти, прежде чем повтор разрешён. По умолчанию
   * считается от размера склада (см. banWindow) — так на маленьком складе
   * волна не встаёт, а на большом не повторяется.
   */
  noRepeat?: number
  /**
   * Трек, который играть НЕЧЕМ (v1.432.0): сломанный, запрещённый сервисом,
   * стриминговый без копии.
   *
   * Зачем это здесь. Волна раньше предлагала такие треки наравне со всеми: в
   * очереди человек видел «дальше — вот эта песня», а плеер, дойдя до неё,
   * обходил её другим правилом — и играло совсем другое. То есть показ и
   * действие расходились, а это в этом проекте самая частая поломка вообще.
   * Теперь одно правило на оба: чего нельзя играть, того волна не предлагает.
   */
  skip?: (t: T) => boolean
}

/**
 * Сколько последних треков нельзя повторять.
 *
 * На складе из трёх треков запрещать все три бессмысленно — играть станет
 * нечего; поэтому окно — три четверти склада, но не больше двадцати: дальше
 * человек всё равно не помнит, что играло.
 */
export function banWindow(restCount: number): number {
  if (restCount <= 1) return 0
  return Math.min(20, Math.max(1, Math.floor(restCount * 0.75)))
}

/** Сколько треков подряд одного исполнителя допустимо. */
export const AUTHOR_STREAK = 2

/** Почему трек предложен — показывается человеку в очереди. */
/**
 * v1.442.0: «давно не слушал» убрано из причин по просьбе владельца.
 *
 * Сама давность в подборе осталась и работает (см. recommend) — без неё волна
 * снова скатится к одной и той же сотне треков. Убрана именно СТРОКА в очереди:
 * «дальше — давно не слушал» человеку ничего не даёт, он и так это знает, а
 * место занимает.
 */
export type Why = 'author' | 'similar' | 'popular' | 'fresh' | 'order'

export const WHY_LABEL: Record<Why, string> = {
  author: 'тот же исполнитель',
  similar: 'похоже на то, что играет',
  popular: 'это часто слушают',
  fresh: 'ещё не слушал',
  order: 'дальше по списку',
}

/**
 * Сколько дней «отдыха» трека дают полный вес (v1.435.0).
 *
 * Месяц: за это время песня успевает забыться, и услышать её снова — радость, а
 * не повтор. Меньше — и волна начнёт возвращать позавчерашнее.
 */
export const RESTED_DAYS = 30

export interface Suggestion<T> { track: T; why: Why; score: number }

/** Слова названия, по которым имеет смысл искать сходство. */
const NOISE = new Set([
  'official', 'video', 'audio', 'lyrics', 'lyric', 'remaster', 'remastered', 'hd', 'the', 'feat', 'ft',
  'prod', 'live', 'version', 'mix', 'remix', 'клип', 'официальный', 'премьера', 'песня',
])
function words(s: string): string[] {
  return (s || '').toLowerCase()
    .replace(/\([^)]*\)|\[[^\]]*\]/g, ' ')
    .split(/[^\p{L}\p{N}]+/u)
    .filter(w => w.length >= 3 && !NOISE.has(w))
}

function norm(s: string | undefined): string {
  return (s || '').toLowerCase().replace(/\s+/g, ' ').trim()
}

/**
 * Подбор следующего — по убыванию пригодности, с объяснением каждой строки.
 * Текущий трек в список не попадает: он уже играет.
 */
export function recommend<T extends QueueTrack>(i: PersonalInput<T>): Suggestion<T>[] {
  const { tracks, idx, plays } = i
  const lastAt = i.lastAt ?? {}
  const recent = i.recent ?? []
  const cur = tracks[idx]
  const skip = i.skip ?? (() => false)
  // Играть нечем — значит и предлагать нечего. Если после отбора не осталось
  // ничего, честно возвращаем пустоту: пусть решает тот, кто спрашивал.
  const rest = tracks.filter((t, n) => n !== idx && !skip(t))
  if (rest.length === 0) return []

  const curAuthor = norm(cur?.author)
  const curWords = new Set(words(cur?.name ?? ''))
  // v1.440.0: та же песня в другой обёртке — это повтор.
  //
  // Очередь не повторялась по id, но ремикс, ускоренная версия и клип одной
  // вещи — это разные id и разные ссылки. Человек слышал одно и то же три раза
  // подряд и справедливо считал очередь сломанной. Ключ песни (songKey.ts)
  // очищает название от пометок версии, и дальше запрет работает по нему.
  const curKey = songKey(cur?.name, cur?.author)
  const keyOf = new Map<string, string>()
  for (const t of tracks) keyOf.set(t.id, songKey(t.name, t.author))
  const bannedKeys = new Set<string>()
  const ban0 = i.noRepeat ?? banWindow(Math.max(1, tracks.length - 1))
  recent.slice(0, ban0).forEach(id => { const k = keyOf.get(id); if (k) bannedKeys.add(k) })
  // v1.440.0: контекст сессии. Раньше через несколько десятков треков волна
  // теряла всякую связь с тем, что человек слушал, и скатывалась к глобально
  // популярному: свежесть кончалась у всего, что рядом, и решать оставалось
  // только числу чужих прослушиваний. Держим исполнителей последних треков —
  // по ним и продолжаем.
  const sessionAuthors = new Set<string>()
  for (const id of recent.slice(0, 12)) {
    const t = tracks.find(x => x.id === id)
    const a = norm(t?.author)
    if (a) sessionAuthors.add(a)
  }
  const pos = new Map(tracks.map((t, n) => [t.id, n]))
  const ban = i.noRepeat ?? banWindow(rest.length)
  // Сколько последних треков подряд — одного исполнителя. Считаем по самой
  // истории: авторов берём из склада, отдельного списка для этого не нужно.
  const authorById = new Map(tracks.map(t => [t.id, norm(t.author)]))
  const streakAuthor = recent.length ? authorById.get(recent[0]) ?? '' : ''
  let streak = 0
  if (streakAuthor) {
    for (const id of recent) {
      if ((authorById.get(id) ?? '') !== streakAuthor) break
      streak++
    }
  }
  const now = i.now ?? Date.now()
  const DAY = 86_400_000

  const out: Suggestion<T>[] = rest.map(t => {
    const mine = plays[t.id] ?? 0
    const sameAuthor = !!curAuthor && norm(t.author) === curAuthor
    const common = words(t.name ?? '').filter(w => curWords.has(w)).length

    let score = 0
    const reasons: [Why, number][] = []

    if (sameAuthor) { score += 100; reasons.push(['author', 100]) }
    if (common > 0) { const v = Math.min(60, 30 * common); score += v; reasons.push(['similar', v]) }

    // v1.435.0: «ты это часто слушаешь» убрано совсем — по прямой просьбе
    // владельца, и она справедлива. Этот сигнал делал ровно обратное тому, зачем
    // очередь нужна: чем чаще песня уже звучала, тем охотнее её ставили снова, и
    // на складе в восемь тысяч треков волна ходила по одной и той же сотне. Это
    // не подбор, а колея.
    //
    // Вместо частоты — ДАВНОСТЬ. Не слушал месяц (RESTED_DAYS) — полный вес; чем
    // свежее прослушивание, тем меньше. Незнакомое — отдельно и сильнее всего:
    // на большом складе главная ценность в том, чего человек ещё не слышал.
    if (mine === 0) {
      score += 55; reasons.push(['fresh', 55])
    } else {
      const at = i.lastAt?.[t.id] ?? 0
      // Даты нет — считаем, что слушал давно: иначе всё, о чём мы не помним
      // когда, навсегда уходило бы вниз.
      const days = at > 0 ? Math.max(0, (now - at) / DAY) : RESTED_DAYS
      // Очки за давность идут, а причиной не называются: см. Why выше.
      score += 40 * Math.min(1, days / RESTED_DAYS)
    }

    // v1.440.0: то же самое, только в другой обёртке, — не предлагаем вовсе.
    const tKey = keyOf.get(t.id) ?? ''
    if (tKey && curKey && tKey === curKey) score -= 10_000
    else if (tKey && bannedKeys.has(tKey)) score -= 5_000

    // Контекст сессии: исполнитель, которого человек уже слушал в этот заход.
    // Слабее прямого совпадения с текущим треком, но именно он не даёт волне
    // скатиться к глобально популярному через полсотни песен.
    if (!sameAuthor && sessionAuthors.has(norm(t.author))) { score += 30; reasons.push(['author', 30]) }

    // Общие прослушивания — только разрешитель ничьих. v1.440.0: вес срезан
    // втрое: на длинной сессии он оказывался единственным работающим сигналом и
    // выносил наверх глобальные хиты, к человеку отношения не имеющие.
    const all = t.plays ?? 0
    if (all > 0) { const v = Math.min(9, 2 * Math.log2(1 + all)); score += v; reasons.push(['popular', v]) }

    // Только что игравшее — НЕЛЬЗЯ, пока не пройдёт окно. Внутри окна
    // сортируем по давности: если запрещено вообще всё (склад из трёх треков),
    // волна возьмёт самое давнее, а не остановится.
    const r = recent.indexOf(t.id)
    if (r >= 0 && r < ban) score -= 10_000 - r * 100
    else if (r >= 0) score -= 60   // за окном повтор разрешён, но всё же не первым делом

    // Третий трек одного исполнителя подряд — это уже «зациклило».
    if (streak >= AUTHOR_STREAK && !!streakAuthor && norm(t.author) === streakAuthor) {
      score -= 200
    }

    reasons.sort((a, b) => b[1] - a[1])
    return { track: t, why: reasons[0]?.[0] ?? 'order', score }
  })

  out.sort((a, b) => {
    if (b.score !== a.score) return b.score - a.score
    const l = (lastAt[b.track.id] ?? 0) - (lastAt[a.track.id] ?? 0)
    if (l !== 0) return l
    return (pos.get(a.track.id) ?? 0) - (pos.get(b.track.id) ?? 0)
  })
  return out
}

/**
 * Прежнее имя — только треки, без объяснений. Остаётся, потому что зовущим его
 * местам объяснение не нужно, а два разных подбора развели бы очередь и то, что
 * реально играет: этим уже обжигались (v1.398.0).
 */
export function personalOrder<T extends QueueTrack>(i: PersonalInput<T>): T[] {
  return recommend(i).map(s => s.track)
}

/**
 * Порядок склада: сначала то, что слушают чаще всего (v1.406.0).
 *
 * Раньше склад выкладывался по времени добавления — это про того, кто когда
 * принёс трек, и человеку, зашедшему послушать, не говорит ничего.
 *
 * При равных числах остаётся прежний порядок: иначе выдача прыгала бы при
 * каждом открытии, а искать глазами в прыгающем списке невозможно.
 */
export function libraryOrder<T extends QueueTrack>(tracks: T[]): T[] {
  const at = new Map(tracks.map((t, n) => [t.id, n]))
  return [...tracks].sort((a, b) => {
    const d = (b.plays ?? 0) - (a.plays ?? 0)
    return d !== 0 ? d : (at.get(a.id) ?? 0) - (at.get(b.id) ?? 0)
  })
}
