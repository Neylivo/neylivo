// v1.426.0: когда прослушивание считается прослушиванием.
//
// Что было. Число росло в тот же миг, когда трек начинал играть: включил — плюс
// один. То есть счётчик говорил не «сколько это слушали», а «сколько раз на это
// нажали». Пролистал двадцать треков по секунде — двадцать прослушиваний, и
// склад «сначала то, что слушают чаще всего» выкладывался по случайным нажатиям.
//
// Как теперь, и это то же правило, что у стриминговых сервисов: считается
// только НАСТОЯЩЕЕ слушание. Если запись короче порога, её надо дослушать
// целиком, иначе засчитать было бы нечего.
//
// v1.428.0 порог был опущен до пятнадцати — я неверно понял просьбу: речь шла не
// о зачёте прослушивания, а о минимальной ДЛИНЕ трека в складе (см.
// music/minLength.ts). Порог вернулся к тридцати, а в v1.435.0 владелец
// попросил поднять его до пятидесяти.
//
// Главная тонкость — перемотка. Проматывать до нужной секунды и получать
// прослушивание нельзя: тогда правило обходится одним движением мыши. Поэтому
// время не берётся из позиции трека, а НАКАПЛИВАЕТСЯ по маленьким шагам:
// сколько секунд позиция ползла сама, столько и слушали. Прыжок вперёд или
// назад — это не шаг, а перемотка: он не прибавляет ничего.
//
// Отдельным файлом и чистыми функциями — потому что проверить это иначе нечем:
// живого «послушал двадцать девять секунд и перемотал» руками не наиграешься.

/**
 * Сколько секунд надо послушать, чтобы это засчиталось.
 *
 * v1.435.0: пятьдесят вместо тридцати — по просьбе владельца. Смысл тот же, но
 * строже: тридцать секунд это ещё «послушал начало», а к пятидесяти песня уже
 * выбрана осознанно. На складе в восемь тысяч треков это заметно: по этому
 * числу строится и порядок склада, и волна, и пролистывание больше в них не
 * попадает вовсе.
 */
export const CREDIT_SEC = 50

/**
 * Самый большой шаг, который считаем обычным ходом песни, а не перемоткой.
 *
 * Позиция приходит от плеера то каждые полсекунды (YouTube), то по событию
 * времени обычного звука. Полторы секунды — с запасом на подвисания и на
 * телефон, который придержал таймеры, и заметно меньше любой осмысленной
 * перемотки.
 */
export const STEP_MAX = 1.5

export interface Listened {
  /** Сколько секунд трек реально звучал. */
  sec: number
  /** Где была позиция в прошлый раз — по ней и считается шаг. */
  pos: number
}

export const freshListened = (pos = 0): Listened => ({ sec: 0, pos: Math.max(0, pos) })

/**
 * Учесть новое положение песни.
 *
 * Прибавляем только положительные шаги не больше STEP_MAX: назад — перемотка,
 * далеко вперёд — тоже перемотка, ноль — плеер стоит.
 */
export function advance(state: Listened, curPos: number): Listened {
  if (!Number.isFinite(curPos) || curPos < 0) return state
  const step = curPos - state.pos
  if (step > 0 && step <= STEP_MAX) return { sec: state.sec + step, pos: curPos }
  // Перемотка или пауза: время не растёт, но новое место запоминаем — иначе
  // следующий обычный шаг посчитался бы от старого места как большой прыжок.
  return { sec: state.sec, pos: curPos }
}

/**
 * Сколько нужно послушать именно этот трек.
 *
 * Короткая запись (короче порога) должна быть доиграна целиком; секунда
 * запаса — на то, что длительность у разных источников округляется по-разному, и
 * без неё короткий трек не засчитывался бы никогда.
 */
export function creditThreshold(dur?: number): number {
  if (!dur || !Number.isFinite(dur) || dur <= 0) return CREDIT_SEC
  return dur < CREDIT_SEC ? Math.max(1, dur - 1) : CREDIT_SEC
}

/** Пора ли засчитывать прослушивание. */
export function credited(state: Listened, dur?: number): boolean {
  return state.sec >= creditThreshold(dur)
}
