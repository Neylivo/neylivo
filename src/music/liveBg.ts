// v1.460.0: живой фон плеера — узор, который меняется под трек.
//
// Что было. Фоном стояла обложка, размытая до пятна. Один трек — одно пятно, и
// пока он играет, на экране ничего не происходит.
//
// Что теперь. Из цвета обложки собирается узор, и он медленно движется. Ключевое
// слово — «медленно»: фон не должен перетягивать внимание с того, ради чего
// открыт плеер.
//
// Почему числа считаются здесь, а не в компоненте. Узор должен быть УСТОЙЧИВЫМ:
// один и тот же трек — один и тот же рисунок, каждый раз. Иначе при любой
// перерисовке пятна прыгали бы по экрану. Устойчивость даёт хеш от ссылки трека,
// а не случайные числа, и это ровно то, что проверяется тестом.
//
// Проверки: src/music/__music_test.ts (npm run test:music).

/** Сколько пятен рисуем. Больше — каша, меньше — не узор, а два кружка. */
export const BLOBS = 5

export interface Blob {
  /** Доля ширины и высоты, 0..1. */
  x: number
  y: number
  /** Размер в долях меньшей стороны. */
  r: number
  /** Насколько сдвигается туда-сюда. */
  amp: number
  /** Длительность круга движения (с) — у каждого своя, иначе они бьются в такт. */
  dur: number
  /** Сдвиг начала (с), чтобы не стартовали разом. */
  delay: number
  /** Прозрачность. */
  alpha: number
}

/** Устойчивое число из строки: одна и та же ссылка — один и тот же узор. */
export function hashOf(s: string): number {
  let h = 2166136261
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return h >>> 0
}

/** Простой предсказуемый генератор: нужен ряд чисел из одного зерна. */
function rng(seed: number) {
  let x = seed || 1
  return () => {
    x ^= x << 13; x >>>= 0
    x ^= x >> 17
    x ^= x << 5; x >>>= 0
    return x / 4294967296
  }
}

/**
 * Узор для трека. Одинаковый вход — одинаковый выход, всегда.
 *
 * @param key   ссылка трека (или что угодно устойчивое)
 * @param speed 0 — стоит на месте (для «выключить анимацию»), 1 — обычная
 */
export function blobsFor(key: string, speed = 1): Blob[] {
  const r = rng(hashOf(String(key ?? '')))
  const out: Blob[] = []
  for (let i = 0; i < BLOBS; i++) {
    out.push({
      x: 0.1 + r() * 0.8,
      y: 0.1 + r() * 0.8,
      r: 0.22 + r() * 0.3,
      amp: 0.04 + r() * 0.07,
      // От 18 до 34 секунд на круг: это заметно глазу как «живое», но не
      // мельтешит. Быстрее — и фон начинает отвлекать от музыки.
      dur: speed > 0 ? (18 + r() * 16) / speed : 0,
      delay: -r() * 20,
      alpha: 0.18 + r() * 0.22,
    })
  }
  return out
}

/** Цвета узора: основной из обложки плюс два соседних оттенка. Без обложки —
 *  цвет темы, чтобы фон не становился серым пятном. */
export function paletteOf(accent: string | null | undefined, fallback = '#5865f2'): string[] {
  const base = (accent || fallback).trim() || fallback
  return [base, shift(base, 28), shift(base, -34)]
}

/** Сдвинуть цвет по светлоте — грубо, но предсказуемо и без библиотек. */
export function shift(hex: string, delta: number): string {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex.trim())
  if (!m) return hex
  const n = parseInt(m[1], 16)
  const ch = [(n >> 16) & 255, (n >> 8) & 255, n & 255]
    .map(v => Math.max(0, Math.min(255, v + delta)))
  return '#' + ch.map(v => v.toString(16).padStart(2, '0')).join('')
}
