// v1.445.0: очередь подгрузки данных о треках — что тянуть первым.
//
// Что было. Данные (название, обложка и, главное, ссылка, по которой трек
// реально играет) тянулись пачками по шестьдесят, а порядок знал ровно про два
// трека: играющий и следующий. Всё остальное шло в порядке склада.
//
// Из-за чего это било по рукам. Человек ищет в Трекотеке «Beatles», получает
// двадцать найденных — и они грузятся последними, потому что лежат где-то в
// середине восьмитысячного склада. То есть ровно то, на что он сейчас смотрит и
// что вот-вот включит, ждёт дольше всего: карточки без обложек, а нажатие на
// трек начинается через паузу, потому что своей ссылки у него ещё нет.
//
// Как теперь. Порядок такой: играющий → следующий → найденное по запросу (в
// порядке выдачи, то есть самое подходящее раньше) → видимое на экране →
// остальное. Данные, уже лежащие в кэше на устройстве, вообще не идут в эту
// очередь: они кладутся сразу и мгновенно (см. seedFromCache).
//
// Проверки: src/music/__music_test.ts (npm run test:music).

/** Сколько тянуть за один заход. Больше — это сотни запросов к чужим сервисам
 *  подряд: они начинают отвечать отказом, а окно всё это время занято. */
export const META_BATCH = 60

export type HasUrl = { url: string }

export type MetaPlanOpts = {
  /** Что играет прямо сейчас. */
  current?: string | null
  /** Что заиграет следующим (по ТОЙ ЖЕ логике, что и кнопка «дальше»). */
  next?: string | null
  /** Найденное по запросу, в порядке выдачи. Пусто — поиска нет. */
  found?: readonly string[]
  /** Что сейчас показано на экране склада. */
  shown?: readonly string[]
  /** Ограничение захода. */
  batch?: number
}

/** Меньше — раньше. Разряды разнесены, чтобы порядок внутри найденного
 *  (по близости к запросу) не перебивал разряды между собой. */
export function metaRank(url: string, o: MetaPlanOpts): number {
  if (o.current && url === o.current) return 0
  if (o.next && url === o.next) return 1
  const f = o.found ? o.found.indexOf(url) : -1
  // Найденное по запросу: разряд 2, внутри — в порядке выдачи, но не больше
  // тысячи позиций, иначе хвост длинной выдачи перелез бы в следующий разряд.
  if (f >= 0) return 2_000 + Math.min(f, 999)
  const s = o.shown ? o.shown.indexOf(url) : -1
  if (s >= 0) return 4_000 + Math.min(s, 999)
  return 9_000
}

/**
 * Что тянуть и в каком порядке. Возвращает не больше batch штук.
 *
 * Порядок устойчив: при равных разрядах сохраняется исходный порядок списка —
 * иначе один и тот же склад планировался бы по-разному от захода к заходу.
 */
export function planMeta<T extends HasUrl>(missing: readonly T[], o: MetaPlanOpts = {}): T[] {
  const batch = o.batch ?? META_BATCH
  if (batch <= 0) return []
  return missing
    .map((t, i) => ({ t, r: metaRank(t.url, o), i }))
    .sort((a, b) => (a.r - b.r) || (a.i - b.i))
    .slice(0, batch)
    .map(x => x.t)
}

/**
 * Данные, которые уже лежат в кэше на устройстве.
 *
 * Зачем отдельно. Кэш у источников есть давно (localStorage в soundcloud.ts и
 * sources.ts), но приложение о нём узнавало только через ту же очередь запросов:
 * каждая карточка ждала своей очереди, чтобы получить то, что и так лежит на
 * диске. Из-за этого обложки на складе проявлялись по одной, хотя тянуть было
 * нечего. Здесь всё лежащее забирается разом и без единого запроса.
 */
export function seedFromCache<M>(
  tracks: readonly HasUrl[], get: (url: string) => M | null,
): Record<string, M> {
  const out: Record<string, M> = {}
  for (const t of tracks) {
    if (out[t.url]) continue
    const m = get(t.url)
    if (m) out[t.url] = m
  }
  return out
}

/** Осталось ли что-то, чего в кэше нет. Пустой ответ значит «запросов не надо
 *  вовсе» — по нему очередь даже не запускается. */
export function needsFetch<T extends HasUrl>(
  missing: readonly T[], seeded: Record<string, unknown>,
): T[] {
  return missing.filter(t => !seeded[t.url])
}
