// v1.430.0: минимальная длина трека в Трекотеке.
//
// Зачем. Склад общий, и в него попадало что угодно: секундные обрезки, звуки
// нажатий, случайно залитые голосовые. В списке они выглядят как песни, в волне
// стоят в очереди наравне со всем остальным, и человек получает подряд десяток
// «треков» по две секунды. Пятнадцать секунд — граница, ниже которой это уже не
// песня, а звук.
//
// Что здесь важно и почему это отдельным файлом с проверками:
//
//   • отказ только когда длина ИЗВЕСТНА. У ссылки на чужой сервис длительности
//     часто нет вовсе, и «отказать на всякий случай» значило бы не пустить в
//     склад половину нормальных треков;
//   • у файла длина читается ДО заливки — иначе короткий обрезок сначала уедет
//     в хранилище, а потом получит отказ, и мусор останется висеть навсегда;
//   • сообщение говорит и правило, и то, что именно не так: «шесть секунд, а
//     нужно хотя бы пятнадцать». Просто «нельзя» человек считает поломкой.

/** Короче этого — не песня, а звук. */
export const MIN_TRACK_SEC = 15

/** Не пустить ли трек в склад. null — можно (в том числе когда длина неизвестна). */
export function tooShortWhy(dur: number | undefined | null): string | null {
  if (dur === undefined || dur === null) return null
  if (!Number.isFinite(dur) || dur <= 0) return null
  if (dur >= MIN_TRACK_SEC) return null
  const sec = dur < 1 ? '1' : String(Math.round(dur))
  return `Слишком короткий трек: ${sec} с, а в Трекотеку берём от ${MIN_TRACK_SEC} с. Это звук, а не песня.`
}

/** Длина аудиофайла в секундах — читается до заливки, по метаданным. */
export function audioDuration(file: File): Promise<number | undefined> {
  return new Promise(res => {
    const a = document.createElement('audio')
    a.preload = 'metadata'
    const done = (v: number | undefined) => { URL.revokeObjectURL(a.src); res(v) }
    a.onloadedmetadata = () => done(Number.isFinite(a.duration) && a.duration > 0 ? a.duration : undefined)
    // Не прочиталось — не повод отказывать: длину проверит уже сам плеер, а
    // ронять добавление из-за неподдерживаемого формата было бы неправильно.
    a.onerror = () => done(undefined)
    // Метаданные иногда не приезжают вовсе (битый файл, редкий формат) — ждать
    // вечно нельзя, иначе добавление просто зависнет.
    window.setTimeout(() => done(undefined), 4000)
    a.src = URL.createObjectURL(file)
  })
}
