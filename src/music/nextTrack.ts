// v1.377.0: что играть после текущего трека.
//
// Зачем отдельным файлом. Это решение жило внутри компонента и потому не
// проверялось ничем — а сломать его можно тихо. Так и вышло: при повторе всего
// списка из одного трека следующий номер совпадал с текущим, состояние не
// менялось, перерисовки не происходило, и вместо повтора наступала тишина.
// Ровно так же молча заканчивалось воспроизведение на последнем треке без
// повтора: номер оставался прежним, «играет» оставалось включённым, а звука не
// было — со стороны это выглядит как зависший плеер.
//
// Поэтому функция ничего не делает сама: она отвечает СЛОВАМИ, что должно
// произойти, а компонент это исполняет. Слова можно проверить тестом.

export type Repeat = 'off' | 'all' | 'one'

export interface NextInput {
  /** Номер текущего трека. */
  idx: number
  /** Сколько всего треков. */
  count: number
  repeat: Repeat
  shuffle: boolean
  /** Номер трека, поставленного в очередь руками. -1 — такого нет. */
  manualIdx?: number
  /** Случайное число [0,1) — передаётся снаружи, чтобы перемешивание проверялось. */
  rnd?: () => number
}

export type NextAction =
  /** Играть трек с этим номером. */
  | { kind: 'go'; index: number }
  /** Тот же трек с начала: номер не меняется, поэтому нужен отдельный ответ. */
  | { kind: 'restart' }
  /** Список кончился, повтора нет — остановиться, а не делать вид, что играем. */
  | { kind: 'stop' }

export function nextTrack(i: NextInput): NextAction {
  const { idx, count, repeat, shuffle } = i
  if (count <= 0) return { kind: 'stop' }

  // Повтор одного — всегда сначала, что бы ни стояло в очереди: человек попросил
  // именно этот трек по кругу.
  if (repeat === 'one') return { kind: 'restart' }

  // Поставленное руками идёт вперёд обычного порядка.
  const m = i.manualIdx ?? -1
  if (m >= 0 && m < count) return m === idx ? { kind: 'restart' } : { kind: 'go', index: m }

  if (count === 1) {
    // Единственный трек: по кругу — только если попросили повтор всего списка.
    return repeat === 'all' ? { kind: 'restart' } : { kind: 'stop' }
  }

  if (shuffle) {
    const r = i.rnd ?? Math.random
    let n = idx
    // Тот же трек подряд при перемешивании — это не случайность, а поломка.
    for (let tries = 0; tries < 20 && n === idx; tries++) n = Math.floor(r() * count)
    if (n === idx) n = (idx + 1) % count
    return { kind: 'go', index: n }
  }

  const n = idx + 1
  if (n < count) return { kind: 'go', index: n }
  return repeat === 'all' ? { kind: 'go', index: 0 } : { kind: 'stop' }
}
