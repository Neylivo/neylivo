// v1.377.0: что играть после текущего трека.
//
// Зачем отдельным файлом. Это решение жило внутри компонента и потому не
// проверялось ничем — а сломать его можно тихо. Так и вышло: при повторе всего
// списка из одного трека следующий номер совпадал с текущим, состояние не
// менялось, перерисовки не происходило, и вместо повтора наступала тишина.
// Ровно так же молча заканчивалось воспроизведение на последнем треке без
// повтора: номер оставался прежним, «играет» оставалось включённым, а звука не
// было — со стороны это выглядит как зависший плеер.
//
// Поэтому функция ничего не делает сама: она отвечает СЛОВАМИ, что должно
// произойти, а компонент это исполняет. Слова можно проверить тестом.

export type Repeat = 'off' | 'all' | 'one'

export interface NextInput {
  /** Номер текущего трека. */
  idx: number
  /** Сколько всего треков. */
  count: number
  repeat: Repeat
  shuffle: boolean
  /** Номер трека, поставленного в очередь руками. -1 — такого нет. */
  manualIdx?: number
  /**
   * Номер трека, который предлагает личная очередь (personalQueue), -1 — нет.
   *
   * v1.398.0: до этой версии личная очередь только рисовалась в панели, а играло
   * приложение всё равно «следующий по складу». То есть список показывал одно, а
   * кнопка делала другое — и это была не мелочь: очередь выглядела сломанной,
   * потому что ею действительно ничего не управлялось. Слабее ручной очереди и
   * повтора одного трека: те человек попросил прямо сейчас.
   */
  personalIdx?: number
  /** Случайное число [0,1) — передаётся снаружи, чтобы перемешивание проверялось. */
  rnd?: () => number
}

export type NextAction =
  /** Играть трек с этим номером. */
  | { kind: 'go'; index: number }
  /** Тот же трек с начала: номер не меняется, поэтому нужен отдельный ответ. */
  | { kind: 'restart' }
  /** Список кончился, повтора нет — остановиться, а не делать вид, что играем. */
  | { kind: 'stop' }

export function nextTrack(i: NextInput): NextAction {
  const { idx, count, repeat, shuffle } = i
  if (count <= 0) return { kind: 'stop' }

  // Повтор одного — всегда сначала, что бы ни стояло в очереди: человек попросил
  // именно этот трек по кругу.
  if (repeat === 'one') return { kind: 'restart' }

  // Поставленное руками идёт вперёд обычного порядка.
  const m = i.manualIdx ?? -1
  if (m >= 0 && m < count) return m === idx ? { kind: 'restart' } : { kind: 'go', index: m }

  if (count === 1) {
    // Единственный трек: по кругу — только если попросили повтор всего списка.
    return repeat === 'all' ? { kind: 'restart' } : { kind: 'stop' }
  }

  // Личная очередь — то, что человек действительно слушает. Перемешивание её
  // отменяет: оно и означает «выбери сам, не по порядку».
  const pers = i.personalIdx ?? -1
  if (!shuffle && pers >= 0 && pers < count && pers !== idx) return { kind: 'go', index: pers }

  if (shuffle) {
    const r = i.rnd ?? Math.random
    let n = idx
    // Тот же трек подряд при перемешивании — это не случайность, а поломка.
    for (let tries = 0; tries < 20 && n === idx; tries++) n = Math.floor(r() * count)
    if (n === idx) n = (idx + 1) % count
    return { kind: 'go', index: n }
  }

  const n = idx + 1
  if (n < count) return { kind: 'go', index: n }
  return repeat === 'all' ? { kind: 'go', index: 0 } : { kind: 'stop' }
}

/**
 * Почему плеер останавливается — словами, чтобы сказать это человеку.
 *
 * `end` — список кончился и повтора нет;
 * `none` — играть нечем: всё, до чего дотянулись, неиграбельно;
 * `repeat-one` — «повтор одного» стоит на треке, который играть нечем.
 */
export type StopWhy = 'end' | 'none' | 'repeat-one'

export type ResolvedNext =
  | { kind: 'go'; index: number }
  | { kind: 'restart' }
  | { kind: 'stop'; why: StopWhy }

/**
 * Что плеер СДЕЛАЕТ дальше с учётом неиграбельных треков (v1.433.0).
 *
 * Зачем отдельно от nextTrack. В v1.432.0 обход неиграбельных треков появился
 * только в исполнении: кнопка «следующий» перешагивала через сломанный трек, а
 * строка «Дальше» в очереди звала ту же nextTrack БЕЗ обхода и показывала
 * именно его. То есть очередь снова обещала одно, а плеер играл другое — ровно
 * та болезнь, которую v1.432.0 и лечила, только заведённая заново на шаг ниже.
 *
 * Поэтому решение целиком, вместе с обходом и остановками, лежит здесь: и показ,
 * и исполнение зовут одну эту функцию, а проверяется она отдельно.
 *
 * `unplayable(i)` отвечает про трек с номером i.
 */
export function resolveNext(i: NextInput & { unplayable: (index: number) => boolean }): ResolvedNext {
  const { idx, count, unplayable } = i
  if (count <= 0) return { kind: 'stop', why: 'end' }

  // Играть нечем вообще — останавливаемся честно, не перебирая склад впустую.
  let anyPlayable = false
  for (let k = 0; k < count; k++) if (!unplayable(k)) { anyPlayable = true; break }
  if (!anyPlayable) return { kind: 'stop', why: 'none' }

  const act = nextTrack(i)
  if (act.kind === 'stop') return { kind: 'stop', why: 'end' }
  if (act.kind === 'restart') {
    // Повторять нечего, если играть нечем: иначе «повтор» крутит молчание.
    return unplayable(idx) ? { kind: 'stop', why: 'repeat-one' } : { kind: 'restart' }
  }
  if (act.index === idx) return unplayable(idx) ? { kind: 'stop', why: 'none' } : { kind: 'restart' }

  let n = act.index
  for (let step = 0; step < count && unplayable(n); step++) n = (n + 1) % count
  // Обошли весь склад и вернулись ни с чем — остановка, а не молчащий трек.
  if (unplayable(n)) return { kind: 'stop', why: 'none' }
  // Обход привёл обратно к играющему: кроме него, играть нечего. Раньше здесь
  // выставлялся тот же номер — состояние не менялось, перерисовки не было, и
  // плеер молча замирал. Повтор списка означает «крути этот», иначе — конец.
  if (n === idx) return i.repeat === 'all' ? { kind: 'restart' } : { kind: 'stop', why: 'none' }
  return { kind: 'go', index: n }
}

/**
 * Куда вернуться по «назад» (v1.407.0).
 *
 * История — стопка того, что играло, наверху лежит играющее сейчас. Шаг назад
 * снимает его и берёт следующее сверху. Треки, которых уже нет в складе (их
 * удалили, пока играла музыка), пропускаются: возвращаться к ним некуда.
 *
 * Раньше «назад» просто уменьшал номер в списке. При перемешивании это была
 * прямая поломка: человек слушал случайный порядок, а возвращался к соседу по
 * складу, которого не слышал вовсе.
 */
export function backTarget(hist: string[], has: (id: string) => boolean): { hist: string[]; target: string | null } {
  const h = hist.slice()
  h.pop()                                        // верхний — это то, что играет сейчас
  while (h.length && !has(h[h.length - 1])) h.pop()
  return { hist: h, target: h.length ? h[h.length - 1] : null }
}
