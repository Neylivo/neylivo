import type { Track } from './types'

/**
 * Свести уже показанный склад с новой порцией (v1.420.0).
 *
 * Порции приходят тремя путями: страницами при открытии плеера, по одному
 * живым событием о чужом треке и пачкой при догоне пропущенного. Раньше на
 * каждый такой случай склад просто перезаписывался целиком — отсюда и рывки, и
 * лишние запросы, и сбитый номер играющего.
 *
 * Правила ровно три, и каждое существует из-за конкретной поломки:
 *
 * 1. Уже известный трек остаётся НА СВОЁМ МЕСТЕ, меняется только его
 *    содержимое. Иначе список перетасовывался бы под играющей песней: номер
 *    играющего считается по этому же массиву.
 * 2. Новое дописывается в конец, в том порядке, в каком приехало. Страницы
 *    приходят по времени добавления, чужой трек — позже всех: получается тот
 *    же порядок, что и раньше, но без перестроения.
 * 3. Повторы внутри самой порции схлопываются: страница и живое событие
 *    запросто приносят один и тот же трек дважды, и без этого он появился бы в
 *    складе двумя карточками.
 */
export function mergeTracks(prev: Track[], incoming: Track[]): Track[] {
  if (!incoming.length) return prev
  const byId = new Map<string, Track>()
  for (const t of incoming) if (t?.id) byId.set(t.id, t)   // повтор в порции — побеждает последний
  if (!byId.size) return prev

  let changed = false
  const out = prev.map(t => {
    const fresh = byId.get(t.id)
    if (!fresh) return t
    byId.delete(t.id)
    if (same(t, fresh)) return t
    changed = true
    return fresh
  })

  // Осталось в byId — то, чего в складе ещё не было.
  for (const t of byId.values()) { out.push(t); changed = true }
  return changed ? out : prev
}

/**
 * Тот же ли это трек по содержимому. Нужен, чтобы не перерисовывать склад из-за
 * события, которое ничего не изменило: чужие клиенты дописывают метаданные
 * (обложку, ссылку) и шлют обновление на каждый такой чих.
 */
function same(a: Track, b: Track): boolean {
  return a.url === b.url && a.name === b.name && a.owner === b.owner
    && a.author === b.author && a.art === b.art && a.dur === b.dur
    && a.play === b.play && a.plays === b.plays
}
