import { useHeaderButtons } from '../lib/plugins/registry'
import { invokePlugin } from '../lib/plugins/bridge'
import { Icon } from './icons'

// v1.467.0: кнопки плагинов в шапке приложения.
//
// Зачем. Мест, откуда плагин мог получить управление, было четыре — команда в
// чате, кнопка у поля ввода, пункт меню сообщения и горячая клавиша, — и все
// они привязаны к переписке. Шапка же видна на любом экране: и в канале сервера,
// и в личке. Именно туда просится всё, что человек хочет нажать «прямо сейчас»,
// не думая, где он сейчас находится.
//
// Рисует кнопку приложение своими руками: плагин присылает только имя иконки из
// закрытого списка и подсказку. Своей разметки в шапке не появляется — ровно по
// той же причине, что и у панелей: подделать чужой элемент интерфейса нельзя.
//
// Один компонент на обе шапки (канал сервера и личка): два одинаковых куска
// разметки однажды разошлись бы, и кнопка появилась бы только в одном месте.
export function PluginHeaderButtons() {
  const btns = useHeaderButtons()
  if (btns.length === 0) return null
  return <>
    {btns.map(b => (
      <button key={b.pluginId + ':' + b.key}
        className={'pin-btn' + (b.active ? ' on' : '')}
        title={b.tooltip + ' — плагин'}
        onClick={() => { void invokePlugin(b.pluginId, b.onClick, []) }}>
        <Icon name={b.icon} size={18} />
      </button>
    ))}
  </>
}
