import React from 'react'
import { createRoot } from 'react-dom/client'
import { Settings } from './Settings'
import { Icon } from './icons'

// Хранилище настроек и профиля подставное: без него компоненты полезут в сеть.
;(window as any).__real_view = true

function Экран() {
  const [что, setЧто] = React.useState<'настройки'>('настройки')
  return (
    <div className="app-viewport">
      {что === 'настройки' && <Settings username="guchipon" avatarUrl={null} onClose={() => setЧто('настройки')} />}
      <span style={{ display: 'none' }}><Icon name="gear" size={12} /></span>
    </div>
  )
}

createRoot(document.getElementById('root')!).render(<Экран />)
