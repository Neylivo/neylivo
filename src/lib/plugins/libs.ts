// Зачем. Владелец просил three.js, babylon, физику и «встроенный npm» — четыре
// пункта из семнадцати про одно и то же. Подключить их с чужого сайта страница
// плагина может и сейчас (обычный script src), но это значит: нужен интернет,
// нужен чужой сервер, и он может однажды отдать не то. Встроенная библиотека
// работает без сети и не зависит ни от кого.
//
// ПОЧЕМУ НЕЛЬЗЯ ПРОСТО import. Страница плагина живёт в песочнице с чужим
// происхождением — той самой, которая не даёт ей добраться до сессии человека.
// Из неё нельзя ни импортировать наш модуль, ни скачать наш файл, ни даже
// выполнить модуль по blob-адресу: браузер отказывается тянуть модуль по такому
// адресу из непрозрачного происхождения (замерено живой пробой, проверка на это
// стоит в __api_test.tsx). Поэтому текст библиотеки едет через мост, а страница
// выполняет его у себя.
//
// Файл с текстами (libsData.ts) грузится ТОЛЬКО когда плагин попросит: у
// человека без плагинов-игр он не нужен вовсе.
//
// Проверки: src/lib/plugins/__test.ts и живая в __api_test.tsx.

/** Одна пара «что экспортируют» — «как оно называется внутри модуля». */
export interface Экспорт { имя: string; локальное: string }

/**
 * Разобрать список экспортов модуля.
 *
 * Собранная библиотека кончается одним большим `export{a as Scene,b as Mesh,…}`.
 * Внутри самого модуля эти значения доступны по ЛОКАЛЬНЫМ именам (a, b), а
 * наружу зовутся иначе. Чтобы собрать из них объект, нужны обе половины.
 *
 * Чистая функция — её и проверяют отдельно, без всякой библиотеки.
 */
/**
 * Где в тексте лежит список экспортов.
 *
 * Возвращает и границы — они нужны withGlobal, чтобы заменить список на месте,
 * а не отрезать всё, что после него.
 */
export function findExportBlock(src: string): { from: number; to: number; body: string } | null {
  // Ищем ПОСЛЕДНИЙ список, после которого нет ничего, кроме пробелов и
  // комментариев.
  //
  // «Просто последний в файле» не годится: сборщик дописывает в самый конец
  // лицензии собранных пакетов блочным комментарием, и список экспортов
  // оказывается НЕ последним. На этом разбор возвращал пустоту, а библиотека
  // молча не выполнялась — «библиотека не выполнилась: three» было всем, что об
  // этом говорилось.
  let последний: { from: number; to: number; body: string } | null = null
  for (const m of src.matchAll(/\bexport\s*\{([^}]*)\}\s*;?/g)) {
    const from = m.index ?? 0
    const to = from + m[0].length
    const хвост = src.slice(to).replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '').trim()
    if (хвост === '') последний = { from, to, body: m[1] }
  }
  return последний
}

export function parseExports(src: string): Экспорт[] {
  const m0 = findExportBlock(src)
  if (!m0) return []
  const m = [null, m0.body] as unknown as RegExpMatchArray
  const out: Экспорт[] = []
  for (const кусок of m[1].split(',')) {
    const ч = кусок.trim()
    if (!ч) continue
    // Имена берём с поддержкой любых букв, а не только латиницы: \w в
    // регулярных выражениях JS — это ровно [A-Za-z0-9_], и на модуле с
    // кириллическим именем разбор молча возвращал пустоту. Своя библиотека
    // автора вполне может быть написана по-русски.
    const пара = /^([\p{L}\p{N}_$]+)\s+as\s+([\p{L}\p{N}_$"']+)$/u.exec(ч)
    if (пара) {
      out.push({ локальное: пара[1], имя: пара[2].replace(/^["']|["']$/g, '') })
    } else if (/^[\p{L}\p{N}_$]+$/u.test(ч)) {
      out.push({ локальное: ч, имя: ч })
    }
  }
  return out
}

/**
 * Переписать модуль так, чтобы он положил себя в window под нужным именем.
 *
 * Список `export{…}` заменяется присваиванием: внутри того же модуля все
 * локальные имена доступны, и объект собирается из них напрямую. Ни один байт
 * самой библиотеки при этом не меняется — только хвост.
 *
 * Почему не оставить export как есть. Импортировать этот модуль странице
 * нечем: он вставляется в неё встроенным <script type="module">, а у
 * встроенного модуля нет адреса, по которому на него можно сослаться.
 */
export function withGlobal(src: string, globalName: string): string {
  const блок = findExportBlock(src)
  const эксп = parseExports(src)
  if (!блок || !эксп.length) {
    // Не модуль (обычный скрипт) — он и так кладёт себя в window сам.
    return src
  }
  const поля = эксп.map(e => JSON.stringify(e.имя) + ':' + e.локальное).join(',')
  // Заменяем НА МЕСТЕ, а не отрезаем хвост: после списка экспортов у собранной
  // библиотеки лежат лицензии её частей, и выбрасывать их нельзя — MIT прямо
  // требует сохранять текст лицензии.
  return src.slice(0, блок.from)
    + ';window[' + JSON.stringify(globalName) + ']={' + поля + '};'
    + src.slice(блок.to)
}

export interface LibInfo {
  id: string
  global: string
  about: string
  /** Сколько весит — человеку на карточке плагина и автору в документации. */
  bytes: number
}

/** Что есть в складе. Грузит тексты по требованию. */
export async function libList(): Promise<LibInfo[]> {
  const { ВСТРОЕННЫЕ } = await import('./libsData')
  return ВСТРОЕННЫЕ.map(b => ({ id: b.id, global: b.global, about: b.about, bytes: b.src.length }))
}

/** Имена без загрузки текстов — для документации и проверок. */
export const LIB_IDS = ['three'] as const

/**
 * Готовый к выполнению текст библиотеки.
 *
 * Отдаётся странице как есть: она вставит его встроенным модулем и заберёт
 * значение из window. Ничего секретного здесь нет — это тот же код, который
 * автор плагина мог бы принести сам.
 */
export async function libSource(id: string): Promise<{ code: string; global: string; kind: string } | null> {
  const { ВСТРОЕННЫЕ } = await import('./libsData')
  const b = ВСТРОЕННЫЕ.find(x => x.id === String(id))
  if (!b) return null
  return { code: withGlobal(b.src, b.global), global: b.global, kind: b.kind }
}
