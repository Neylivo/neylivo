export interface PluginManifest {
  id: string            // латиница/цифры/дефис, уникален — по нему хранится и обновляется
  name: string
  version: string       // semver-подобная строка, для сравнения при обновлении
  author: string
  description: string
  permissions: Permission[]
  hosts: string[]       // домены для 'net'; без 'net' игнорируется
  /** Своя картинка плагина, https (v1.349.0). Пусто — рисуется значок по умолчанию. */
  icon: string | null
  /** Шапка карточки плагина, https. Пусто — мягкая заливка от акцента. */
  banner: string | null
}

export interface InstalledPlugin {
  manifest: PluginManifest
  code: string
  enabled: boolean
  installedAt: string   // ISO
  /** Откуда приехал — для строки «от @ник» в списке. null = поставлен из файла. */
  sourceUserId: string | null
  /**
   * Сделан здесь, в конструкторе (v1.363.0).
   *
   * Раньше «свой» вычислялось по совпадению @author с твоим ником — но автора
   * пишет тот, кто собрал плагин, и чужой плагин с твоим именем в шапке попадал
   * в «Свои». Пометку ставит только конструктор, подделать её из файла нельзя.
   * Необязательное: у плагинов, поставленных до этой версии, его нет, и для них
   * работает прежнее правило.
   */
  authoredHere?: boolean
  /** Настройки самого плагина (то, что он пишет через ponoi.storage). */
  storage: Record<string, unknown>
}

/** Ошибка разбора .ponoi-файла — текст показывается человеку как есть. */
export class PluginParseError extends Error {}
