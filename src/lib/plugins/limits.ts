// v1.489.0: пределов у плагинов больше НЕТ.
//
// Прямое указание владельца: «убери полностью все ограничение плагинов».
// Это второй шаг: в v1.446.0 по его же просьбе числа были подняты в десятки раз
// («чтобы было абсолютно свободно, но предупреждения были»), а теперь сняты
// совсем.
//
// ЧТО ИМЕННО УБРАНО. Всё, что считало, СКОЛЬКО плагину можно: частота
// сообщений, реакций, запросов в интернет, число кнопок, команд, окон, холстов,
// файлов, таблиц, соединений, размеры значений и самого файла плагина. Ничего
// из этого больше не проверяется нигде.
//
// ЧТО ОСТАЛОСЬ И ПОЧЕМУ. Только сроки ожидания — константы ниже. Это не
// «сколько плагину можно», а «сколько приложение ждёт ответа». Разницу провёл
// сам владелец, когда описывал «Архитектуру без границ»: код плагина живёт в
// отдельном потоке, и `while (true)` внутри него обязан вешать ПЛАГИН, а не
// приложение. Убери сроки — и первый же не ответивший плагин повесил бы
// отправку сообщений намертво: человек не смог бы ни написать, ни дойти до
// кнопки «выключить». Это не ограничение плагина, это граница между ним и
// приложением.
//
// Проверки: src/lib/plugins/__test.ts и __attack_test.ts.

const SEC = 1000
const MIN = 60 * SEC

/**
 * Сколько ждать ответа от плагина.
 *
 * Щедро: плагин с моделью думает долго, и «не успел» не должно выглядеть как
 * «сломан». Но не бесконечно — см. объяснение выше.
 */
export const INIT_TIMEOUT_MS = 60 * SEC
export const INVOKE_TIMEOUT_MS = 10 * MIN

/**
 * Сеть: сколько ждать чужой сервер.
 *
 * Тоже срок, а не квота: запрос, который не завершится никогда, оставил бы за
 * собой висящее соединение и незакрытый поток в самом приложении.
 */
export const NET_TIMEOUT_MS = 120 * SEC
export const NET_STREAM_MS = 15 * MIN
export const NET_STREAM_IDLE_MS = 120 * SEC

/** Текст предупреждения — показывается перед установкой и на карточке. */
export const LIMITS_WARNING =
  'У плагинов нет ограничений: этот плагин может писать сообщения, ставить реакции, ходить в '
  + 'интернет и работать в фоне сколько угодно и как угодно часто. Отвечать за всё, что он '
  + 'сделает от твоего имени, будешь ты, а не плагин. Ставь только то, чему доверяешь, и '
  + 'выключай, если поведение стало странным.'

/** Короткая строка для карточки — там места на абзац нет. */
export const LIMITS_WARNING_SHORT = 'Ограничений нет — плагин действует от твоего имени'
