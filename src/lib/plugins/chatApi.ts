// v1.419.0: что плагин может делать с перепиской открытого чата.
//
// Раньше плагин видел ровно то, что происходило ПРИ НЁМ: событие «пришло
// сообщение» и больше ничего. Ни прочитать то, что уже на экране, ни поставить
// реакцию, ни убрать своё сообщение он не мог. То есть половина простых
// задумок («посчитай, о чём тут говорили», «ставь 👍 на упоминания меня»,
// «убери мою опечатку») упиралась не в безопасность, а в отсутствие способа.
//
// Почему мост, а не прямые запросы в базу из api.ts. Всё, что здесь есть,
// делает НЕ плагин, а тот самый экран, который человек видит перед собой: и
// реакция, и удаление идут теми же обработчиками, что и нажатие мышью, со
// всеми их проверками прав канала. Плагин не получает ни доступа к базе, ни
// возможности дотянуться до чата, который сейчас не открыт.
//
// Ключ моста — id открытого разговора (канал сервера или диалог). Он же
// приходит плагину в ponoi.channel(). Так «показ и действие» считаются одним и
// тем же: плагин читает и правит ровно тот чат, про который приложение сказало
// ему «этот сейчас открыт», а не тот, который последним отрисовался.

export interface ChatMsgInfo {
  id: string
  author: string
  authorName: string
  content: string
  /** Твоё ли это сообщение — плагину иначе не отличить своё от чужого. */
  mine: boolean
  /** Когда отправлено, ISO. */
  at: string
}

export interface ChatBridge {
  /** Последние сообщения открытого чата — те же, что на экране. */
  recent: (limit: number) => ChatMsgInfo[]
  /** Поставить или снять реакцию. Возвращает причину отказа или null. */
  react: (messageId: string, emoji: string) => Promise<string | null>
  /** Убрать сообщение. Причина отказа или null. Чужое убрать нельзя. */
  remove: (messageId: string) => Promise<string | null>
}

const bridges = new Map<string, ChatBridge>()

/** Чат открылся (или закрылся) — сообщает об этом сюда. key — id канала или диалога. */
export function setChatBridge(key: string, b: ChatBridge | null) {
  if (b) bridges.set(key, b)
  else bridges.delete(key)
}

export function chatBridge(key: string | null | undefined): ChatBridge | null {
  return key ? bridges.get(key) ?? null : null
}

/** Сколько сообщений плагин может забрать за раз: столько же примерно и на экране. */
export const MAX_RECENT = 50
