// v1.469.0: правило «чей сейчас контекст» — одним местом.
//
// Полей ввода на экране одновременно до трёх: личка, канал сервера и открытая
// ветка — все смонтированы разом. Если бы каждое просто присваивало контекст на
// своём рендере, побеждало бы отрисованное последним, и плагин писал бы не в тот
// чат, который человек видит. Это была настоящая поломка (v1.293.0), и правило
// придумано ровно против неё: владельцем становится то поле, с которым человек
// работает последним (по фокусу), а на пустое место может встать любое.
//
// Почему правило переехало сюда. С этой версии система плагинов грузится не
// сразу, а когда плагины действительно есть (см. bridge.ts). Значит, до её
// загрузки кто-то должен помнить, чей контекст сейчас, — и делать это по ТОМУ ЖЕ
// правилу. Две копии правила разошлись бы, и вернулась бы та самая поломка:
// плагин пишет не в тот чат. Поэтому копия одна, и её же использует host.ts.
//
// Проверки: src/lib/plugins/__test.ts.

export class CtxHolder<T> {
  private owner: string | null = null
  private value: T

  constructor(private readonly empty: T) { this.value = empty }

  /** force — «я тот, с кем человек работает прямо сейчас», перебивает чужое владение. */
  claim(owner: string, next: T, force: boolean): void {
    if (!force && this.owner !== null && this.owner !== owner) return
    this.owner = owner
    this.value = next
  }

  release(owner: string): void {
    if (this.owner !== owner) return
    this.owner = null
    this.value = this.empty
  }

  current(): T { return this.value }
  currentOwner(): string | null { return this.owner }
  /** Есть ли кому передавать — нужно при передаче состояния настоящему хосту. */
  has(): boolean { return this.owner !== null }
}
