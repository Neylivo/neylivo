    // сырые байты
    const buf = await ponoi.assets.get('sprite.png')     // ArrayBuffer
    // звуком (нужно ещё notify), громкость 0…1 в пределах общей громкости
    await ponoi.assets.play('hit.mp3', 0.6)
    // картинкой в панели или в настройках
