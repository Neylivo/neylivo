// v1.531.0: длина сообщения больше ничего не выдаёт.
//
// Владелец: «сделай лучшую шифровку в мире без потери скорости и качества»,
// и отдельно — про фиксированную длину: «расшифровка даже не знает, отправлен
// ли один символ или тысяча».
//
// ЧТО УТЕКАЛО. Сам текст был закрыт и раньше: содержимое читают только
// устройства собеседника. Но ДЛИНА шифротекста повторяла длину текста почти
// байт в байт. Тот, кто видит базу или трафик, не читая ни слова, узнавал:
//   • «да» это или страница текста;
//   • ссылка это или одно слово (по характерной длине);
//   • сколько человек печатал в переписке за вечер.
// В разговоре «да/нет» этого достаточно, чтобы прочесть ответ, не расшифровав
// ни одного байта.
//
// ЧТО ТЕПЕРЬ. Перед шифрованием текст кладётся в блок ФИКСИРОВАННОГО размера:
// сначала длина, потом сам текст, потом настоящий случайный шум до края блока.
// Снаружи любое сообщение выглядит одинаково.
//
// ПОЧЕМУ БЛОК НЕ ОДИН, А ЛЕСЕНКОЙ. Один размер на всё — это либо 1 КБ на «да»
// (и тогда длинное сообщение всё равно не влезет, придётся резать), либо
// огромный блок ради каждой запятой. Поэтому ступени: 1 КБ, 4, 16, 64, 256 КБ и
// дальше мегабайтами. Ступень видно снаружи, но она говорит лишь «сообщение
// короче килобайта» — а это одинаково верно и для «да», и для абзаца.
// Плата за скрытность при этом честная: короткое сообщение весит килобайт, а не
// три байта. Для переписки это ничто, а для тех, кто смотрит со стороны, разница
// между «да» и «нет» исчезает.
//
// ПОЧЕМУ ШУМ НАСТОЯЩИЙ, А НЕ НУЛИ. Нули сжались бы в ничто, если бы кто-нибудь
// (например, база или прокси) применил сжатие к шифротексту, — и длина снова
// стала бы видна. Случайные байты не сжимаются.
//
// СКОРОСТЬ. Ничего нового не считается: та же одна операция шифрования, просто
// над блоком фиксированной длины. Замер — в src/lib/crypto/__test.ts.
//
// СОВМЕСТИМОСТЬ. Старые сообщения без блока читаются как раньше: у блока есть
// метка в первых байтах, и разбор смотрит на неё, а не гадает.

/** Метка блока: две буквы и версия. Их не бывает в начале обычного текста. */
const МЕТКА = [0x50, 0x64, 0x01] // 'P', 'd', 1

/** Ступени размеров, байты. Первая — самая частая: короткие реплики. */
export const STEPS = [
  1024,
  4 * 1024,
  16 * 1024,
  64 * 1024,
  256 * 1024,
  1024 * 1024,
]

/** Заголовок: метка (3) + длина текста (4 байта, старшим вперёд). */
const HEAD = МЕТКА.length + 4

/** Какой блок возьмём под столько байт текста. */
export function stepFor(len: number): number {
  const надо = len + HEAD
  for (const s of STEPS) if (надо <= s) return s
  // Длиннее самой большой ступени — округляем вверх до мегабайта, чтобы и у
  // огромных сообщений соседние размеры совпадали.
  const мб = 1024 * 1024
  return Math.ceil(надо / мб) * мб
}

/**
 * Положить текст в блок постоянного размера.
 *
 * Шум берётся у системного источника случайности — того же, что даёт ключи.
 */
export function pad(text: string, random: (n: number) => Uint8Array = случайные): Uint8Array {
  const тело = new TextEncoder().encode(text)
  const размер = stepFor(тело.length)
  const блок = new Uint8Array(размер)
  // Сначала шум на весь блок, потом поверх — заголовок и текст. Так не остаётся
  // ни одного байта, который мы забыли заполнить.
  блок.set(random(размер))
  блок.set(МЕТКА, 0)
  const dv = new DataView(блок.buffer, блок.byteOffset)
  dv.setUint32(МЕТКА.length, тело.length, false)
  блок.set(тело, HEAD)
  return блок
}

/**
 * Достать текст обратно.
 *
 * Нет метки — значит это старое сообщение, отправленное до этой версии:
 * читаем как есть. Молчать и отдавать пустоту в таком случае нельзя — переписка
 * до обновления просто исчезла бы с экрана.
 */
export function unpad(bytes: Uint8Array): string {
  if (bytes.length >= HEAD && МЕТКА.every((b, i) => bytes[i] === b)) {
    const dv = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength)
    const len = dv.getUint32(МЕТКА.length, false)
    // Длина, не помещающаяся в блок, значит порчу: лучше отдать пустоту, чем
    // прочитать чужой шум как текст.
    if (HEAD + len <= bytes.length) {
      return new TextDecoder().decode(bytes.subarray(HEAD, HEAD + len))
    }
    return ''
  }
  return new TextDecoder().decode(bytes)
}

function случайные(n: number): Uint8Array {
  const b = new Uint8Array(n)
  // crypto.getRandomValues берёт не больше 65536 за раз — режем на куски.
  for (let i = 0; i < n; i += 65536) {
    crypto.getRandomValues(b.subarray(i, Math.min(i + 65536, n)))
  }
  return b
}
