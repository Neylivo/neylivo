// v1.505.0: что открывается по нажатию на текущую активность.
//
// Владелец: «статистика сюжетной игры должна открываться нажатием на текущую
// активность в мини-профиле». В мини-профиле карточка «Играет в» не открывала
// ничего вовсе — панель существовала, но добраться до неё можно было только
// через полный профиль. Теперь оба места спрашивают ЗДЕСЬ, и разойтись им
// нельзя: это тот самый разлад «экран считает одно, кнопка делает другое»,
// который в этом проекте уже ломал вещи не раз.
//
// Второе, что решается здесь же: ЧЬИ данные мы вправе показать.
//
// Панель прохождения читает список вех с ЭТОГО устройства — с диска и из
// памяти приложения. Для своей активности это правильно. Для чужой — нет: там
// лежит МОЁ прохождение той же игры, и открыть его под чужим именем значит
// показать выдумку. Поэтому чужая карточка открывается, только если человек сам
// делится своим местом в игре (оно приходит в присутствии), и панель тогда
// показывает ровно то, чем он делится.
//
// Проверки: src/lib/__ui_test.ts (npm run test:ui).

export type ActivityPanel = 'stats' | 'campaign' | 'shared' | null

export interface PanelAsk {
  /** Название игры из активности. */
  game: string
  /** Своя это активность или чужая. */
  isMe: boolean
  /** У игры есть отслеживаемые матчи (CS2, Dota 2 — см. MATCH_TRACKED_GAMES). */
  matchTracked: boolean
  /** Настройка приватности статистики матчей у владельца активности. */
  statsVisibility?: string | null
  /** Человек делится местом в сюжете — эти числа приходят в присутствии. */
  sharesStory?: boolean
}

/**
 * Что открыть.
 *
 * `stats`    — статистика матчей за 30 дней (сетевые игры).
 * `campaign` — прохождение: вехи с диска, свои отметки и заметки. Только своё.
 * `shared`   — чужое прохождение: ровно то, чем человек поделился, без правки.
 * `null`     — открывать нечего, и карточка не должна прикидываться нажимаемой.
 *
 * У СВОЕЙ игры null не бывает никогда. Это прямое требование владельца — «должно
 * работать как угодно»: если вех не нашлось, панель откроется и скажет, чего
 * именно не хватает, а не промолчит нажатием в пустоту. Дверь, которая иногда
 * не открывается, хуже двери, за которой пусто.
 */
export function panelFor(a: PanelAsk): ActivityPanel {
  if (!a.game) return null
  if (a.matchTracked && (a.isMe || a.statsVisibility !== 'none')) return 'stats'
  if (a.isMe) return 'campaign'
  return a.sharesStory ? 'shared' : null
}

/** Подпись при наведении — из того же решения, чтобы обещание совпало с делом. */
export function panelTitle(p: ActivityPanel): string | undefined {
  if (p === 'stats') return 'Статистика за 30 дней'
  if (p === 'campaign') return 'Прохождение: вехи, проценты и заметки'
  if (p === 'shared') return 'Прохождение — то, чем делится игрок'
  return undefined
}
