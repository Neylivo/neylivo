// v1.508.0: человеку — по-человечески. Внутренности приложения наружу не идут.
//
// Владелец: «убрать из приложения лишние данные, которые не надо знать
// пользователям».
//
// ЧТО ИМЕННО ВЫЛЕЗАЛО. Два вида.
//
//   1. Указания владельцу базы. Строк вроде «Канал не удалился: примени
//      миграцию supabase/29_channels_update_policy.sql» в приложении было два
//      десятка. Обычному человеку это не говорит НИЧЕГО: ни файла у него нет,
//      ни доступа к базе, ни повода знать, что она вообще есть. Зато он узнаёт
//      номер и имя внутреннего файла — то, чего знать не должен.
//
//   2. Отказы базы как есть. В восьмидесяти с лишним местах стояло
//      `toastErr(String(error.message ?? error))`, и человек получал в лицо
//      «new row violates row-level security policy for table "channels"» или
//      «duplicate key value violates unique constraint». Это текст для того,
//      кто пишет запросы, а не для того, кто нажал кнопку.
//
// ПОЧЕМУ ОДНА ВОРОНКА, А НЕ ПРАВКА СТА МЕСТ. Правка ста мест — это сто шансов
// пропустить одно и ещё столько же в следующей версии: каждый новый
// `toastErr(error.message)` вернул бы всё назад. Здесь же чинится путь, по
// которому отказы доходят до экрана, и новые места чинятся сами.
//
// ЧТО СТАНОВИТСЯ С ПОДРОБНОСТЯМИ. Они не пропадают: их видит владелец при
// включённом режиме разработчика и всегда — консоль. Убрать причину поломки
// совсем значило бы чинить следующую вслепую.
//
// Проверки: src/lib/__ui_test.ts (npm run test:ui).

/** Признаки того, что текст писала база или наш же разработчик, а не человек. */
const ТЕХНИЧЕСКОЕ: [RegExp, string][] = [
  // Нет доступа — самое частое, и оно же самое понятное человеку.
  [/row-level security|permission denied|not authorized|insufficient privilege/i,
   'Не хватает прав на это действие'],
  [/duplicate key|unique constraint|already exists/i,
   'Такое уже есть'],
  [/violates foreign key|violates check constraint|null value in column/i,
   'Не получилось сохранить — данные не подошли'],
  // Нет таблицы или столбца: у человека это выглядит как «не сохраняется».
  [/column .* does not exist|relation .* does not exist|schema cache|PGRST\d+|could not find/i,
   'Сейчас это не сохраняется'],
  [/JWT|invalid token|token is expired|refresh_token/i,
   'Сеанс устарел — войди заново'],
  [/failed to fetch|networkerror|network request failed|ERR_[A-Z_]+/i,
   'Нет связи с сервером'],
  [/timeout|timed out/i,
   'Сервер долго не отвечает'],
]

/** Хвост «примени миграцию …» — указание владельцу базы, а не человеку. */
const МИГРАЦИЯ = /\s*[—\-:,.]?\s*(?:сначала\s+)?примени(?:те)?\s+миграци[июы][^]*$/i

/** Упоминание внутреннего файла базы где угодно в строке. */
const ФАЙЛ_БАЗЫ = /supabase\/[\w./-]+/gi

const ЗАПАСНОЕ = 'Не получилось'

export interface Очищенное {
  /** Что показать человеку. */
  видно: string
  /** Что убрано — для консоли и режима разработчика. Пусто, если убирать было нечего. */
  спрятано: string
}

/**
 * Убрать из сообщения то, чего человеку знать не надо.
 *
 * Возвращает и показанное, и спрятанное: спрятанное не выбрасывается, а уходит
 * в консоль — иначе следующую поломку пришлось бы искать вслепую.
 */
export function humanFail(текст: unknown): Очищенное {
  const исходный = String(
    текст && typeof текст === 'object' && 'message' in (текст as Record<string, unknown>)
      ? (текст as { message?: unknown }).message ?? текст
      : текст ?? '',
  ).trim()
  if (!исходный) return { видно: ЗАПАСНОЕ, спрятано: '' }

  // 1. Отказ базы целиком — от него человеку не нужно ни слова.
  for (const [есть, человеку] of ТЕХНИЧЕСКОЕ) {
    if (есть.test(исходный)) return { видно: человеку, спрятано: исходный }
  }

  // 2. Наша же строка с указанием про миграцию: оставляем начало, где сказано,
  //    ЧТО не вышло, и срезаем хвост про файл.
  if (МИГРАЦИЯ.test(исходный) || ФАЙЛ_БАЗЫ.test(исходный)) {
    const начало = исходный.replace(МИГРАЦИЯ, '').replace(ФАЙЛ_БАЗЫ, '').trim()
      .replace(/[\s—\-:,]+$/, '')
    return { видно: начало.length >= 8 ? начало : ЗАПАСНОЕ, спрятано: исходный }
  }

  return { видно: исходный, спрятано: '' }
}

/** Короткий путь: только то, что видно человеку. */
export const humanText = (текст: unknown): string => humanFail(текст).видно
