// v1.460.0: что приложение пишет в консоль.
//
// Что было. Ошибки печатались как есть: `console.error('[roles] load failed:', e)`
// — то есть в консоль ложился весь объект ошибки, а местами и сами данные. В
// одном месте прямо печатался кусок настроек человека (patchUserPrefs), в
// другом — объект ошибки входа. У собранного приложения консоль открывает кто
// угодно: и тот, кому дали посмотреть, и тот, кто снимает экран.
//
// Как теперь. Один приём на всё приложение:
//   • наружу уходит ТОЛЬКО короткое сообщение об ошибке, без объектов и без
//     данных, которые к ней приложили;
//   • в собранном приложении подробностей нет вовсе — остаётся метка места,
//     чтобы по жалобе можно было понять, где искать;
//   • при разработке всё печатается как раньше: там это и нужно.
//
// Чего это НЕ делает: не прячет ошибки от самого приложения. Показ человеку —
// это toast с понятной причиной, он никуда не девался.
//
// Проверки: src/lib/__ui_test.ts (npm run test:ui).

/** Собранное приложение (Vite подставляет это на сборке). */
const PROD = (() => {
  try { return !!(import.meta as any).env?.PROD } catch { return false }
})()

/** Короткая причина из чего угодно. Объекты не разворачиваем: именно в них и
 *  приезжает лишнее — запросы, заголовки, куски данных. */
export function shortReason(e: unknown): string {
  if (e == null) return ''
  if (typeof e === 'string') return e.slice(0, 200)
  const m = (e as any)?.message
  if (typeof m === 'string' && m) return m.slice(0, 200)
  return 'ошибка без описания'
}

/** Что уйдёт в консоль. Отдельной функцией, чтобы это можно было проверить, не
 *  засоряя вывод проверок. */
export function logLine(tag: string, e: unknown, prod = PROD): string {
  return prod ? `[${tag}]` : `[${tag}] ${shortReason(e)}`
}

/** Записать ошибку. Никаких вторых доводов: всё, что можно сказать, — в строке. */
export function logErr(tag: string, e?: unknown) {
  try { console.error(logLine(tag, e)) } catch { /* консоли может не быть */ }
}

export function logWarn(tag: string, e?: unknown) {
  try { console.warn(logLine(tag, e)) } catch { /* консоли может не быть */ }
}
