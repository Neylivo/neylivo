// v1.358.0: когда сообщение считается длинным и сворачивается.
//
// Отдельным файлом, потому что это правило, а не оформление: от него зависит,
// увидит человек кнопку «Показать полностью» или нет, и проверять его надо
// отдельно от разметки.
//
// Считаем по строкам и символам, а не по настоящей высоте: высоту пришлось бы
// мерить уже после отрисовки, а сообщения приходят пачками — лента дёргалась бы
// на каждой.

/** Столько строк помещается на экран, дальше уже простыня. */
export const LONG_LINES = 22
/** Длинный абзац без переносов занимает столько же места. */
export const LONG_CHARS = 1800

export function isLongText(t: string): boolean {
  if (!t) return false
  if (t.length > LONG_CHARS) return true
  let nl = 0
  for (let i = 0; i < t.length; i++) if (t[i] === '\n' && ++nl > LONG_LINES) return true
  return false
}
