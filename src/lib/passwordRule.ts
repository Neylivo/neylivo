// v1.557.0 (находка F8 аудита): свой порог пароля.
//
// ЧТО БЫЛО. Своей проверки не было вовсе: приложение отправляло что угодно и
// только РАЗБИРАЛО ответ сервера («password should be at least»). Порог при
// этом — умолчание Supabase, шесть символов, и человек узнавал о нём после
// отправки, ошибкой на чужом языке, переведённой у нас в одну строку.
//
// ЧТО ТЕПЕРЬ. Правило живёт здесь, отдельной чистой функцией — потому что
// проверять его надо без браузера, а показывать в двух местах (подсказка под
// полем и отказ при отправке), и разъезжаться этим двум местам нельзя.
//
// Разбор ответа сервера при этом ОСТАЁТСЯ: порог в проекте может быть строже
// нашего, и тогда последнее слово всё равно за ним.
//
// Чего здесь намеренно нет: требований «одна заглавная, одна цифра, один
// значок». Они добавляют мороки больше, чем стойкости, — человек отвечает на
// них «Password1!», и это хуже длинной строчки из трёх слов.

/** Ниже этого не пускаем. Восемь — то, что советуют и NIST, и OWASP. */
export const MIN_PASSWORD = 8

/** Пароли, которые подбираются первыми же попытками. Список короткий
 *  намеренно: это отсечка совсем очевидного, а не проверка по словарю. */
const ОЧЕВИДНЫЕ = new Set([
  'password', 'passw0rd', '12345678', '123456789', '1234567890', 'qwertyui',
  'qwerty123', 'iloveyou', 'princess', 'football', 'baseball', 'sunshine',
  'superman', 'trustno1', 'starwars', 'whatever', 'computer', 'freedom',
  'пароль123', 'йцукенг', 'йцукенгш',
])

/**
 * Что не так с паролем. null — всё в порядке.
 *
 * @param пароль что ввели
 * @param рядом  почта и юзернейм: пароль не должен их повторять
 */
export function паролеваяБеда(пароль: string, рядом: string[] = []): string | null {
  if (пароль.length < MIN_PASSWORD) {
    return `Пароль короче ${MIN_PASSWORD} символов. Длина здесь важнее «сложности»: три обычных слова подряд надёжнее, чем «Pa$$w0rd».`
  }
  const н = пароль.toLowerCase()
  if (ОЧЕВИДНЫЕ.has(н)) return 'Этот пароль подбирают первым же перебором — придумай другой.'
  // Один символ на весь пароль («aaaaaaaa») длины не добавляет.
  if (new Set(пароль).size <= 2) return 'В пароле всего один-два разных символа — такой подбирается мгновенно.'
  for (const x of рядом) {
    const ч = (x || '').trim().toLowerCase()
    const имя = ч.includes('@') ? ч.slice(0, ч.indexOf('@')) : ч
    if (имя.length >= 3 && н.includes(имя)) {
      return 'Пароль повторяет твою почту или юзернейм — их знает и тот, кто будет его подбирать.'
    }
  }
  return null
}

/** Подсказка под полем, пока человек печатает. Пустая строка — не показывать. */
export function паролеваяПодсказка(пароль: string): string {
  if (!пароль) return `Не короче ${MIN_PASSWORD} символов.`
  if (пароль.length < MIN_PASSWORD) return `Ещё ${MIN_PASSWORD - пароль.length} симв.`
  return ''
}
