// v1.545.0: большие файлы — частями.
//
// Владелец: «щас супабейс не даёт ни клип сохранить и вообще ничего… сделай
// чтобы даже без зависимости серверов загружались файлы больше 45 МБ».
//
// В ЧЁМ БЕДА. Хранилище принимает ОДИН объект ограниченного размера — на
// бесплатном тарифе это полсотни мегабайт. Приложение при этом разрешало файлы
// до сорока гигабайт: человек выбирал клип на сто мегабайт, ждал загрузки и
// получал отказ сервера. Хуже всего, что отказ приходил в конце, а не в начале.
//
// ЧТО ДЕЛАЕМ. Режем файл на куски по 45 МБ и отправляем их как отдельные
// объекты, а рядом кладём опись: имя, тип, размер и список кусков. Получатель
// скачивает куски и склеивает обратно — байт в байт. Предел на один объект
// перестаёт что-либо значить: в хранилище больше нет ни одного объекта крупнее
// куска.
//
// Здесь чистая часть: сколько кусков, какие имена, как выглядит опись и что
// считается негодной описью. Загрузка и склейка — в bigUpload.ts, потому что там
// нужна сеть, а это можно проверить числами (npm run test:ui).

/**
 * Предел на один кусок.
 *
 * 45, а не 50: у хранилища предел считается по телу запроса вместе с
 * заголовками, и файл ровно в пятьдесят мегабайт уже не проходит. Пять
 * мегабайт запаса — плата за то, чтобы не выяснять это на чужом клипе.
 */
export const КУСОК = 45 * 1024 * 1024

/** Опознавательное окончание описи. По нему приложение понимает, что перед ним
 *  не файл, а список кусков. */
export const РАСШИРЕНИЕ = '.ponoipart'

export interface BigManifest {
  /** Версия описи:формат ещё может поменяться, и старые описи должны читаться. */
  v: 1
  /** Настоящее имя файла — то, что человек увидит при скачивании. */
  name: string
  /** Настоящий тип. В хранилище у кусков он обезличен. */
  type: string
  /** Общий размер в байтах. По нему проверяется, что склеили всё. */
  size: number
  /** Адреса кусков ПО ПОРЯДКУ. Перестановка даёт битый файл. */
  parts: string[]
}

/** Нужно ли резать этот файл. */
export function надоРезать(size: number): boolean {
  return size > КУСОК
}

/** Сколько кусков выйдет. */
export function сколькоКусков(size: number): number {
  if (!isFinite(size) || size <= 0) return 0
  return Math.ceil(size / КУСОК)
}

/**
 * Границы куска номер n: [начало, конец).
 *
 * Последний кусок короче остальных — это нормально и на склейку не влияет,
 * потому что порядок и общий размер записаны в описи.
 */
export function границы(size: number, n: number): { от: number; до: number } {
  const от = n * КУСОК
  return { от, до: Math.min(size, от + КУСОК) }
}

/** Имя куска в хранилище. Нули впереди — чтобы порядок читался и глазами. */
export function имяКуска(n: number): string {
  return 'part' + String(n).padStart(4, '0')
}

/** Похоже ли, что по этому адресу лежит опись, а не файл. */
export function этоОпись(url: string): boolean {
  return typeof url === 'string' && url.split(/[?#]/)[0].endsWith(РАСШИРЕНИЕ)
}

/**
 * Проверить опись, пришедшую из сети.
 *
 * Опись лежит в хранилище и приходит как обычный ответ сервера — то есть это
 * данные извне, и верить им нельзя. Особенно списку адресов: по нему приложение
 * пойдёт скачивать, и подсунуть туда можно что угодно.
 */
export function годнаяОпись(x: unknown, ждатьХост?: string): x is BigManifest {
  if (!x || typeof x !== 'object') return false
  const o = x as Record<string, unknown>
  if (o.v !== 1) return false
  if (typeof o.name !== 'string' || !o.name) return false
  if (typeof o.type !== 'string') return false
  if (typeof o.size !== 'number' || !isFinite(o.size) || o.size <= 0) return false
  if (!Array.isArray(o.parts) || !o.parts.length || o.parts.length > 4096) return false
  for (const p of o.parts) {
    if (typeof p !== 'string' || !p) return false
    // Только http(s) и только тот же хост, откуда пришла сама опись: иначе
    // описью можно заставить приложение ходить куда угодно чужими руками.
    let u: URL
    try { u = new URL(p) } catch { return false }
    if (u.protocol !== 'https:' && u.protocol !== 'http:') return false
    if (ждатьХост && u.host !== ждатьХост) return false
  }
  // Размер должен сходиться с числом кусков: опись, обещающая гигабайт двумя
  // кусками, либо испорчена, либо подделана.
  const ожидаемо = сколькоКусков(o.size as number)
  if ((o.parts as string[]).length !== ожидаемо) return false
  return true
}

/** Собрать опись для файла. */
export function опись(name: string, type: string, size: number, parts: string[]): BigManifest {
  return { v: 1, name, type, size, parts }
}

/** Человеческий размер для подписи «файл на 1,2 ГБ». */
export function размерСловами(b: number): string {
  if (!isFinite(b) || b < 0) return '—'
  if (b < 1024) return b + ' Б'
  if (b < 1024 ** 2) return (b / 1024).toFixed(0) + ' КБ'
  if (b < 1024 ** 3) return (b / 1024 ** 2).toFixed(1).replace('.', ',') + ' МБ'
  return (b / 1024 ** 3).toFixed(2).replace('.', ',') + ' ГБ'
}

/**
 * Отказ хранилища — про размер?
 *
 * Пределы у разных проектов свои, и узнать их заранее неоткуда. Поэтому обычная
 * отправка, упавшая на размере, переходит на куски — но только если упала
 * ИМЕННО на размере, а не на правах или сети.
 */
export function отказПоРазмеру(e: unknown): boolean {
  const t = String((e as { message?: string })?.message || e || '').toLowerCase()
  if (/\b413\b/.test(t)) return true
  return /payload too large|entity too large|maximum allowed size|exceeded the maximum|file size|too large/i.test(t)
}
