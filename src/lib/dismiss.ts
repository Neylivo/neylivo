// v1.460.0: всплывающие панели закрываются щелчком мимо.
//
// Что было. Выбор эмодзи и гифок закрывался ТОЛЬКО повторным нажатием на тот же
// значок или крестиком внутри. Щелчок мимо не делал ничего — панель висела
// поверх переписки, и чтобы от неё избавиться, надо было вспомнить, откуда она
// взялась, и попасть в тот же маленький значок. Так не ведёт себя ни одна
// всплывающая панель ни в одном приложении.
//
// Почему правило вынесено отдельно. «Щелчок мимо» — это не одна проверка, а
// три, и каждая из них про свою беду:
//
//   • сам открывающий значок не считается «мимо». Иначе нажатие по нему
//     закрывало бы панель тем же событием, которым открыло, — и она бы не
//     открылась вовсе (или мигнула);
//   • щелчок ВНУТРИ панели не считается «мимо», даже если попал по её краю или
//     по вложенному окошку;
//   • нажатие Escape закрывает — это привычно и не требует целиться.
//
// Проверки: src/lib/__ui_test.ts (npm run test:ui).

/** Узел, по которому щёлкнули, лежит внутри одного из данных? */
export function insideAny(target: unknown, roots: readonly (Element | null | undefined)[]): boolean {
  const el = target as Element | null
  // Проверяем ровно то, чем пользуемся ниже, — contains. Раньше здесь стоял
  // страж на closest, которого этот код не зовёт вовсе: он молча отвергал бы
  // любой узел без него, и «щелчок внутри панели» считался бы щелчком мимо.
  if (!el) return false
  for (const r of roots) {
    if (!r) continue
    if (r === el) return true
    if (typeof (r as any).contains === 'function' && r.contains(el)) return true
  }
  return false
}

/**
 * Закрывать ли панель по этому нажатию.
 *
 * panel — сама панель, trigger — значок, которым её открыли. Оба могут
 * отсутствовать: панель ещё не отрисовалась, значок мог исчезнуть.
 */
export function shouldDismiss(target: unknown, panel?: Element | null, trigger?: Element | null): boolean {
  return !insideAny(target, [panel, trigger])
}
