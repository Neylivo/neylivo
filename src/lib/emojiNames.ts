export interface EmojiName { name: string; char: string }

// Двоеточие внутри слова трогать нельзя — иначе «https://» и «12:30» открывали бы
// список на ровном месте, поэтому перед ним требуем начало строки или пробел.
// Двух букв ждём намеренно: на одной совпадает слишком многое и подсказка только
// мешает печатать.
const TAIL = /(?:^|\s):([\p{L}\p{N}_+-]{2,32})$/u

/**
 * Что человек сейчас набирает после «:», или null, если подсказку показывать не надо.
 * Смотрим только на текст слева от курсора — как это делает и подсказка упоминаний.
 */
export function emojiQueryAt(text: string, caret: number): string | null {
  const m = text.slice(0, caret).match(TAIL)
  return m ? m[1] : null
}

/** Плоский список «имя → символ»: одно имя — одна строка подсказки. */
export const EMOJI_NAMES: EmojiName[] = RAW.flatMap(([names, char]) =>
  names.split(' ').map(name => ({ name, char })))

/** Поиск по началу имени — как в Discord: печатаешь начало, получаешь список. */
export function searchEmojiNames(q: string, limit = 8): EmojiName[] {
  const t = q.trim().toLowerCase()
  if (!t) return []
  const out: EmojiName[] = []
  const seen = new Set<string>()
  // Сначала совпадения с начала имени, потом вхождения где угодно: так «ог»
  // даёт «огонь» раньше, чем «многоточие».
  for (const pass of [0, 1]) {
    for (const e of EMOJI_NAMES) {
      if (out.length >= limit) return out
      if (seen.has(e.char)) continue
      const i = e.name.indexOf(t)
      if (pass === 0 ? i !== 0 : i <= 0) continue
      seen.add(e.char)
      out.push(e)
    }
  }
  return out
}
