// v1.362.0: чем именно не удался вход — ошибся человек или отвалилась сеть.
//
// Зачем отдельно. От этого различения зависит, выпустит ли приложение человека
// из аккаунта без пароля. Если принять неверный пароль за обрыв связи, выход
// без пароля станет доступен любому, кто нажмёт кнопку дважды, — то есть защита
// исчезнет, оставшись на вид целой. Поэтому правило вынесено сюда и проверяется
// отдельно от разметки.
//
// Определяем именно СЕТЬ, а всё непонятное считаем отказом: ошибиться в сторону
// «не выпустить» безопасно, в обратную — нет.

const NETWORK = /network|fetch|timeout|econn|enotfound|abort|offline|502|503|504/i

export type AuthFailure = 'wrong-password' | 'network'

export function classifyAuthError(message: unknown): AuthFailure {
  const m = String(message ?? '')
  // Supabase на неверный пароль отвечает «Invalid login credentials» — в этой
  // строке нет ни одного сетевого слова, и она честно попадёт в отказ.
  return NETWORK.test(m) ? 'network' : 'wrong-password'
}
