// v1.510.0: клавиатура на телефоне не закрывается от нажатия кнопок ввода.
//
// Владелец: «написание сообщения на телефонах удобнее, как в Discord и TG».
//
// ЧТО БЫЛО. Набираешь сообщение, жмёшь синюю «отправить» — и фокус уходит с
// поля на кнопку. Экранная клавиатура при этом закрывается, лента прыгает на
// освободившееся место, и чтобы написать следующее сообщение, надо снова
// целиться в поле и ждать, пока клавиатура выедет обратно. В переписке, где
// сообщений подряд десяток, это десять лишних тычков и десять прыжков экрана.
// Ни Discord, ни Telegram так себя не ведут: там клавиатура остаётся.
//
// ПОЧЕМУ ИМЕННО pointerdown. Фокус переносит браузер, и делает это ПО УМОЛЧАНИЮ
// на нажатии, а не на щелчке. Отменить перенос можно только там же — в
// pointerdown (или mousedown). Возвращать фокус после отправки поздно: на
// Android клавиатура к этому мигу уже поехала вниз, и обратно она приезжает
// рывком.
//
// ЧТО ПРИ ЭТОМ НЕ ЛОМАЕТСЯ. Отмена относится только к переносу фокуса —
// нажатие проходит как обычно и кнопка срабатывает. Поэтому вешать это можно
// лишь на кнопки, которым фокус не нужен самим: отправить, эмодзи, микрофон. На
// поле ввода, ссылки и пункты меню — нельзя.
//
// Проверки: npm run test:composer (настоящие события указателя в окне).

/**
 * Не отдавать фокус этой кнопке.
 *
 * Возвращает true, если перенос фокуса был отменён, — по нему проверка и
 * отличает работу от бездействия.
 */
export function keepFocus(e: { preventDefault: () => void; target?: unknown }): boolean {
  // Внутри самого поля ввода отменять нечего: там фокус и нужен.
  const цель = e.target as { closest?: (s: string) => unknown } | null
  if (цель && typeof цель.closest === 'function' && цель.closest('textarea, input, [contenteditable="true"]')) {
    return false
  }
  e.preventDefault()
  return true
}
