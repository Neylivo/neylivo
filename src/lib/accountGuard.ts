export const REPORT_REASONS = [
  { id: 'spam', label: 'Спам или реклама' },
  { id: 'abuse', label: 'Оскорбления или травля' },
  { id: 'threat', label: 'Угрозы или опасное поведение' },
  { id: 'illegal', label: 'Запрещённый контент' },
  { id: 'other', label: 'Другое' },
] as const

export type ReportReason = typeof REPORT_REASONS[number]['id']

export interface ReportDraft {
  target: string
  reason: ReportReason | ''
  note: string
}

/**
 * Готова ли жалоба к отправке.
 *
 * Причина обязательна, а «Другое» без пояснения — это пустая жалоба, по которой
 * ничего нельзя сделать: такую лучше не принимать, чем принять и не разобрать.
 */
export function reportReady(d: ReportDraft): boolean {
  if (!d.target || !d.reason) return false
  if (d.reason === 'other') return d.note.trim().length >= 10
  return true
}

/** Длина пояснения, которую хранит база. Длиннее — обрезаем, а не отказываем. */
export const REPORT_NOTE_MAX = 1000

export function reportNote(note: string): string {
  return String(note || '').trim().slice(0, REPORT_NOTE_MAX)
}
