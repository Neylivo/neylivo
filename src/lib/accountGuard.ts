/**
 * Правило подтверждения: человек должен ввести своё имя пользователя.
 *
 * Не «вы уверены?»: на такое отвечают «да» не читая. Ввод имени — маленькая
 * работа, которую невозможно сделать случайно, и она же показывает, что человек
 * понимает, чей аккаунт удаляет.
 */
export function deleteConfirmed(typed: string, username: string): boolean {
  return typed.trim().toLowerCase() === String(username || '').trim().toLowerCase()
    && !!String(username || '').trim()
}

