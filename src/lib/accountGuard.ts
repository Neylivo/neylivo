// v1.533.0: удаление аккаунта, жалобы и задержки на опасные действия.
//
// Владелец принёс список требований Google Play к мессенджерам и отдельно —
// защиту уровня Steam. Здесь ПРАВИЛА: что и через сколько происходит. Работа с
// базой и разметка — отдельно, потому что правила должны проверяться числами.
//
// ПОЧЕМУ ЗАДЕРЖКА, А НЕ «УДАЛИТЬ СРАЗУ». Если аккаунт увели, первое, что делает
// чужой человек, — стирает следы: меняет почту, ключи, удаляет переписку.
// Мгновенное удаление ему в этом помогает. Задержка переворачивает картину:
// у настоящего владельца есть окно, чтобы вернуться и отменить, а у чужого
// человека нет способа его пропустить.
//
// ПОЧЕМУ РАЗНЫЕ СРОКИ. Удаление аккаунта необратимо — семь дней. Смена почты и
// ключей обратима, но опасна — три дня. Выход из всех сеансов не опасен вовсе и
// делается сразу: он ЗАЩИЩАЕТ, и заставлять человека ждать, пока чужой читает
// его переписку, было бы жестокостью.
//
// Проверки: src/lib/__ui_test.ts (npm run test:ui).

export type GuardAction =
  /** Полное удаление аккаунта и всех данных. */
  | 'delete'
  /** Смена привязанной почты. */
  | 'email'
  /** Смена ключей шифрования (все прежние переписки станут нечитаемыми). */
  | 'keys'
  /** Выход со всех устройств. */
  | 'logout-all'

const ДЕНЬ = 24 * 60 * 60 * 1000

/** Сколько ждать до исполнения, миллисекунды. Ноль — сразу. */
export const HOLD_MS: Record<GuardAction, number> = {
  delete: 7 * ДЕНЬ,
  email: 3 * ДЕНЬ,
  keys: 3 * ДЕНЬ,
  'logout-all': 0,
}

export interface HoldState {
  action: GuardAction
  /** Когда запросили, мс. */
  at: number
}

/** Когда это исполнится. */
export function holdUntil(h: HoldState): number {
  return h.at + (HOLD_MS[h.action] ?? 0)
}

/** Пора ли исполнять. */
export function holdDue(h: HoldState, now = Date.now()): boolean {
  return now >= holdUntil(h)
}

/** Сколько осталось ждать, миллисекунды. Ноль — уже пора. */
export function holdLeft(h: HoldState, now = Date.now()): number {
  return Math.max(0, holdUntil(h) - now)
}

/**
 * Человеческая подпись на баннере.
 *
 * Считается ОДНОЙ функцией и для баннера, и для письма, и для кнопки: три
 * места, каждое со своим округлением, дали бы «осталось 2 дня» на баннере и
 * «3 дня» в письме, и человек не знал бы, чему верить.
 */
export function holdLabel(h: HoldState, now = Date.now()): string {
  const мс = holdLeft(h, now)
  if (мс <= 0) return 'можно исполнять'
  const часы = Math.ceil(мс / (60 * 60 * 1000))
  if (часы >= 48) return 'осталось ' + Math.ceil(часы / 24) + ' дн.'
  if (часы >= 2) return 'осталось ' + часы + ' ч'
  const мин = Math.ceil(мс / 60000)
  return 'осталось ' + мин + ' мин'
}

