// v1.484.0: отправлять ли сообщение по нажатию Enter.
//
// Владелец принёс: «когда вставляешь сообщение на телефон, оно не должно
// сразу отправляться». Так и было: обычный Enter отправлял всегда, а на
// телефоне ровно такое событие приходит не только от человека.
//
// ОТКУДА БЕРЁТСЯ ЛОЖНЫЙ ENTER НА ТЕЛЕФОНЕ. Экранная клавиатура работает не как
// настоящая: она НАБИРАЕТ текст (composition), а потом подтверждает его. При
// вставке из буфера, автозамене и подсказке слова браузер шлёт события, среди
// которых оказывается и Enter — человек при этом ничего не нажимал. На
// компьютере такого не бывает, поэтому поломка и не была видна.
//
// Как теперь. На телефоне Enter — это ПЕРЕНОС СТРОКИ, как во всех
// мессенджерах: отправка — кнопкой. На компьютере всё как было: Enter или
// Ctrl+Enter, смотря по настройке. И на обеих — ни одной отправки, пока
// клавиатура ещё набирает слово.
//
// Проверки: npm run test:ui.

export interface KeyState {
  /** Нажат Ctrl или Cmd. */
  ctrl: boolean
  /** Нажат Shift — это всегда перенос строки. */
  shift: boolean
  /** Клавиатура ещё набирает слово (IME, автозамена, вставка на телефоне). */
  composing: boolean
  /** Телефон или планшет. */
  mobile: boolean
  /** Настройка «чем отправлять»: Enter или Ctrl+Enter. */
  sendKey: 'enter' | 'ctrl'
}

/**
 * Отправлять ли по этому нажатию Enter.
 *
 * Правило целиком, одной функцией: раньше оно было разбросано по условиям
 * прямо в обработчике, и «на телефоне не отправлять» пришлось бы дописывать в
 * два места сразу.
 */
export function shouldSend(k: KeyState): boolean {
  // Набор ещё идёт — не наше событие. Это самая частая причина «отправилось
  // само»: подтверждение слова экранной клавиатурой выглядит как Enter.
  if (k.composing) return false
  // Shift+Enter — перенос строки везде и всегда.
  if (k.shift) return false
  if (k.ctrl) return true
  // Обычный Enter: на компьютере — по настройке, на телефоне — никогда.
  if (k.mobile) return false
  return k.sendKey !== 'ctrl'
}

/** Вставляет ли это нажатие перенос строки (то есть мы НЕ мешаем браузеру). */
export const isNewline = (k: KeyState): boolean => !shouldSend(k)

/**
 * Клавиатура ещё набирает слово.
 *
 * Отдельной функцией и в общем месте: этот признак нужен КАЖДОМУ полю, которое
 * отправляет по Enter, а три копии одной проверки рано или поздно разойдутся.
 * isComposing понимают современные браузеры, keyCode 229 — все остальные.
 */
export function isComposingKey(e: { nativeEvent?: unknown }): boolean {
  const n = e.nativeEvent as { isComposing?: boolean; keyCode?: number } | undefined
  return n?.isComposing === true || n?.keyCode === 229
}
