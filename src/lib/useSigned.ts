import { useEffect, useState } from 'react'
import { подписать, разложить } from './attachUrl'

// v1.557.0: адрес вложения для показа — подписанный, если это наше хранилище.
//
// Отдельным файлом от attachUrl.ts, чтобы тот оставался обычным модулем без
// React: его логику (разбор адреса, склейка пачки) проверяют в Node, и тянуть
// туда рендерер ради одного хука незачем.

/**
 * Что подставлять в src/href.
 *
 * Пока подпись не приехала, отдаётся ИСХОДНЫЙ адрес, а не пустота. Это
 * осознанно: бакет сейчас публичный, исходный адрес работает, и картинка
 * появляется сразу — без мигания пустым местом на каждой ленте. Когда бакет
 * закроют, первый кадр покажет сломанную картинку на ~100 мс до прихода
 * подписи, и вот тогда исходный адрес перестанет годиться — поэтому ЗАКРЫВАТЬ
 * бакет можно только вместе с переводом этого места на ожидание (об этом прямо
 * написано в supabase/111_storage_private.sql).
 */
export function useSigned(url: string | null | undefined): string | null | undefined {
  const надо = !!url && !!разложить(url)
  const [готово, setГотово] = useState<string | null>(null)

  useEffect(() => {
    if (!надо || !url) { setГотово(null); return }
    let жив = true
    подписать(url).then((u) => { if (жив) setГотово(u) }).catch(() => {})
    return () => { жив = false }
  }, [url, надо])

  if (!url) return url
  return готово ?? url
}
