// v1.443.0: когда телефону проверять обновление и когда качать его заранее.
//
// Что было. Проверка происходила ровно один раз — при запуске приложения. На
// телефоне приложение неделями не запускается заново, его сворачивают и
// разворачивают; значит, о вышедшей версии человек узнавал только после того,
// как система выгрузит приложение из памяти. А когда узнавал — жал «Обновить» и
// ждал скачивания десятков мегабайт, глядя на проценты.
//
// Как теперь. Проверка повторяется: по возвращении в приложение и раз в
// несколько часов. Файл обновления скачивается заранее и сам — но ТОЛЬКО по
// сети без тарификации: «оно само скачало 60 МБ» на мобильном интернете — это
// не забота, а неприятность. Когда файл уже лежит, кнопка становится
// «Установить» и срабатывает мгновенно.
//
// Чего здесь нет и не будет: молчаливой подмены приложения. Android спрашивает
// согласие на установку поверх — и правильно делает.
//
// Проверки: src/lib/__ui_test.ts (npm run test:ui).

/** Не чаще раза в 6 часов — чаще нет смысла, релизы выходят не поминутно. */
export const OTA_EVERY_MS = 6 * 60 * 60 * 1000
/** Но если приложение было свёрнуто дольше получаса — проверить при возврате. */
export const OTA_RESUME_MS = 30 * 60 * 1000

export type OtaState = {
  now: number
  /** Когда последний раз ходили на сервер за списком релизов (0 — никогда). */
  lastCheck: number
  /** Приложение только что вернулось из фона. */
  resumed: boolean
  /** Версия, которую человек закрыл крестиком. */
  dismissed: string | null
  /** Найденная версия (null — ещё не искали или обновления нет). */
  found: string | null
  /** Версия, файл которой уже скачан и лежит на диске. */
  ready: string | null
  /** Сеть с тарификацией (мобильный интернет). */
  metered: boolean
  /** Есть ли сеть вообще. */
  online: boolean
  /** Идёт скачивание прямо сейчас. */
  busy: boolean
}

export type OtaAction = 'idle' | 'check' | 'download'

/** Что делать прямо сейчас. Одна функция и для расписания, и для показа — так
 *  кнопка «Установить» не может появиться раньше, чем файл действительно есть. */
export function otaDecide(s: OtaState): OtaAction {
  if (!s.online || s.busy) return 'idle'

  // Нашли новее того, что скачано, сеть без тарификации — качаем молча.
  if (s.found && s.found !== s.ready && !s.metered) return 'download'

  // Пора ли снова спросить сервер.
  const since = s.now - s.lastCheck
  if (s.lastCheck === 0) return 'check'
  if (s.resumed && since >= OTA_RESUME_MS) return 'check'
  if (since >= OTA_EVERY_MS) return 'check'
  return 'idle'
}

/** Что показывать в карточке. null — карточки нет. */
export function otaBanner(s: OtaState): { version: string; ready: boolean } | null {
  if (!s.found) return null
  if (s.dismissed === s.found) return null
  return { version: s.found, ready: s.ready === s.found }
}

/** Скачанный файл от прошлой версии больше не нужен: он уже не поставится
 *  поверх, а место занимает. */
export function otaStale(ready: string | null, found: string | null): boolean {
  return !!ready && ready !== found
}
