// v1.298.0: 3D-питомцы профиля. Раньше библиотека подключалась скриптом с
// ajax.googleapis.com прямо в index.html — то есть при КАЖДОМ запуске приложения,
// даже у тех, кто ни одного трёхмерного питомца не увидит.
//
// Чем это было плохо для приложения, которое мы делаем приватным:
//   • каждый запуск сообщал Google адрес и время — ещё до входа в аккаунт;
//   • чужой код с чужого сервера исполнялся с полными правами внутри окна, где
//     теперь лежит расшифрованная переписка: подмена на стороне CDN означала бы
//     полный доступ к ней;
//   • без интернета приложение тянуло скрипт, которого не получит.
//
// Теперь библиотека лежит у нас и подгружается только тогда, когда на экране
// действительно появляется 3D-питомец.

let loading: Promise<unknown> | null = null

export function ensureModelViewer(): Promise<unknown> {
  // Регистрация веб-компонента <model-viewer> — побочный эффект импорта. Повторный
  // вызов безопасен: промис один на всё приложение.
  if (!loading) loading = import('@google/model-viewer').catch(err => {
    // Не удалось — питомец просто не покажется объёмным. Это не повод ронять профиль.
    console.warn('3D-питомец недоступен:', err)
  })
  return loading
}
