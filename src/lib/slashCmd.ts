// v1.356.0: разбор слэш-команды в поле ввода.
//
// Зачем отдельным файлом. Здесь жила настоящая поломка: команды ботов искались
// регуляркой с \w, а \w — это только латиница, цифры и подчёркивание. Все
// готовые боты («Кубик», «Опросы», «Шар предсказаний») называют свои команды
// по-русски: /кубик, /опрос, /шар. Поэтому подсказка на «/ку» не появлялась
// никогда, а набранное целиком «/кубик» уходило в чат обычным текстом — бот
// выглядел мёртвым, хотя работал.
//
// У команд плагинов такую же ошибку уже чинили (там \p{L}), а ботов забыли. В
// разметке это была одна строчка, которую нельзя было проверить; здесь она
// проверяется тестом.

/**
 * Что человек набирает после «/», пока команда ещё не дописана до пробела.
 * Возвращает начало имени (можно пустое — сразу после «/») или null, если это
 * вообще не команда.
 */
export function slashPrefix(text: string): string | null {
  const m = /^\/([\p{L}\p{N}_-]*)$/u.exec(text)
  return m ? m[1].toLowerCase() : null
}

/**
 * Готовая команда с остатком строки: «/выбери чай | кофе» → имя и «чай | кофе».
 * Команда обязана быть в самом начале сообщения — как в Discord.
 */
export function parseSlash(text: string): { name: string; rest: string } | null {
  const m = /^\/([\p{L}\p{N}_-]+)(?:\s+([\s\S]*))?$/u.exec(text.trim())
  return m ? { name: m[1].toLowerCase(), rest: (m[2] ?? '').trim() } : null
}

/**
 * Доводы команды: то, что человек написал после имени (v1.359.0).
 *
 * Раньше здесь было только позиционное раскладывание по options — и у готовых
 * ботов всё написанное после команды пропадало бесследно. Их команды заводятся
 * с пустым options (см. bot-create), поэтому цикл не выполнялся ни разу:
 * «/шар завтра дождь?» приходил к боту без вопроса вовсе, и тот отвечал
 * «задай вопрос», как будто его не задавали.
 *
 * Поэтому хвост строки всегда идёт ещё и целиком, под именем text — его и ждут
 * встроенные боты (bot-interact: args.text ?? args.arg ?? args.value). Заодно
 * это единственный способ передать довод с пробелами: «/выбери чай | кофе»
 * позиционным разбором превратилось бы в одно слово «чай».
 */
export function buildArgs(rest: string, options: { name: string }[]): Record<string, string> {
  const args: Record<string, string> = {}
  const parts = rest.split(/\s+/).filter(Boolean)
  options.forEach((o, i) => { if (parts[i] !== undefined) args[o.name] = parts[i] })
  // Не затираем одноимённый описанный довод: если команда сама объявила text,
  // её разбор главнее нашей подстраховки.
  if (rest && args.text === undefined) args.text = rest
  return args
}

// ── Доводы команды и подсказки к ним (v1.475.0) ─────────────────────────────
//
// Зачем. Команда плагина умела ровно одно: получить хвост строки текстом.
// Человек, набравший «/опрос», видел пустоту и должен был откуда-то знать, что
// писать дальше. Теперь плагин описывает доводы, а приложение показывает их
// прямо в поле ввода и подсказывает значения.
//
// Разбор — чистой функцией, потому что именно здесь легко ошибиться незаметно:
// «какой довод сейчас набирается» зависит от пробела в конце, а «последний
// довод забирает остаток» — от того, что доводов может быть меньше, чем слов.

/** Один довод команды — то, что объявил плагин. */
export interface CmdArg {
  name: string
  description?: string
  required?: boolean
  placeholder?: string
  /** Готовые значения. Если их нет, спрашиваем плагин (onComplete). */
  options?: { value: string; label: string }[]
}

export interface ArgState {
  /** Значения по именам доводов. Последний довод забирает весь остаток. */
  values: Record<string, string>
  /** Какой довод человек набирает прямо сейчас (-1 — уже ни одного). */
  current: number
  /** Что он успел набрать в этом доводе. */
  prefix: string
}

/**
 * Разложить хвост строки по доводам.
 *
 * Правило «последний забирает остаток» — не мелочь: без него «/напомни через
 * час позвонить маме» теряло бы всё после первого пробела, и плагин получал бы
 * «позвонить» вместо «позвонить маме».
 */
export function splitArgs(rest: string, args: CmdArg[]): ArgState {
  const values: Record<string, string> = {}
  if (args.length === 0) return { values, current: -1, prefix: '' }

  const хвостПоследнему = (i: number) => i === args.length - 1
  const части = rest.split(/\s+/)
  // Пробел в конце означает «этот довод дописан, идёт следующий».
  const дописан = /\s$/.test(rest) || rest === ''
  const набрано = rest.trim() === '' ? 0 : части.filter(Boolean).length

  let оставшееся = rest.trimStart()
  for (let i = 0; i < args.length; i++) {
    if (хвостПоследнему(i)) {
      if (оставшееся.trim()) values[args[i].name] = оставшееся.trim()
      break
    }
    const m = /^(\S+)(\s+)?([\s\S]*)$/.exec(оставшееся)
    if (!m) break
    // Слово считается дописанным доводом, только если после него есть пробел:
    // иначе человек ещё его печатает.
    if (!m[2] && !дописан) break
    values[args[i].name] = m[1]
    оставшееся = m[3]
  }

  const current = дописан
    ? Math.min(набрано, args.length - 1)
    : Math.min(Math.max(набрано - 1, 0), args.length - 1)
  const prefix = дописан ? '' : (части[части.length - 1] ?? '')
  return { values, current, prefix }
}

/** Подпись подсказки: «/имя <довод> <довод>» с выделенным текущим. */
export function argHint(args: CmdArg[], current: number): { name: string; on: boolean; req: boolean }[] {
  return args.map((a, i) => ({ name: a.name, on: i === current, req: !!a.required }))
}
