// v1.511.0: пока идёт игра, приложение не отъедает у неё машину.
//
// Владелец: «полная оптимизация с анализом текущей игры без потери качества».
//
// ЧТО ТРАТИЛОСЬ ВПУСТУЮ. NeyLivo живёт свёрнутым часами: человек играет, а
// приложение продолжает делать всё то же, что и на экране. Самое дорогое —
// петли по кадрам: спектр звука считается шестьдесят раз в секунду (чтение
// анализатора, разбор по полосам, перерисовка), живой фон плеера рисуется тем
// же темпом. Плюс опросы по таймеру: присутствие, «что играет», позиция трека.
// Всё это идёт, даже когда смотреть на него некому, и отнимает то же время у
// игры, которая идёт на переднем плане.
//
// ЧТО ЗДЕСЬ РЕШАЕТСЯ. Одно правило: беречь ресурсы, только когда СОШЛИСЬ ТРИ
// вещи — идёт игра, окно приложения не видно и человек в нём не работает. Любая
// из них отпала — возвращаемся к обычной работе немедленно.
//
// «БЕЗ ПОТЕРИ КАЧЕСТВА» — это про то, что бережный режим НЕ ВКЛЮЧАЕТСЯ, пока
// приложение на экране. Никаких «на телефоне рисуем пореже», никакого
// ухудшения картинки ради цифр. Экономится ровно то, чего в этот миг никто не
// видит: кадры для невидимого окна и опросы, которые подождут.
//
// ПОЧЕМУ НЕ ПОЛАГАЕМСЯ НА САМ БРАУЗЕР. Chromium приглушает страницу, когда окно
// скрыто, — но только скрыто. Окно, оставленное позади игры на втором экране
// или просто не в фокусе, для него живое, и петли крутятся на полной скорости.
// А ещё приглушение браузера не трогает наши таймеры сети.
//
// Проверки: src/lib/__ui_test.ts (правило) и npm run test:save (настоящие кадры).

export interface GameState {
  /** Запущена игра (это знает рабочий стол — см. neylivoDesktop.onGame). */
  gameRunning: boolean
  /** Окно приложения видно на экране. */
  visible: boolean
  /** Человек работает в приложении прямо сейчас. */
  focused: boolean
  /** Настройка «беречь ресурсы во время игры». Выключена — бережём никогда. */
  enabled: boolean
}

/**
 * Беречь ли ресурсы прямо сейчас.
 *
 * Бережём, только когда идёт игра И окно не на виду И в нём не работают.
 * Достаточно одному условию отпасть — работаем как обычно.
 */
export function saving(s: GameState): boolean {
  if (!s.enabled) return false
  if (!s.gameRunning) return false
  return !s.visible && !s.focused
}

/**
 * Во сколько раз реже делать повторяющуюся работу.
 *
 * Не «в сто раз» и не «никогда»: приложение обязано остаться живым. Сообщения
 * приходят сами (подписка), а вот опросы можно растянуть — вчетверо. Проверено
 * тем, что присутствие с шестидесяти секунд уезжает на четыре минуты: друзья
 * по-прежнему видят человека в сети, а машина отдыхает.
 */
export const SAVE_SLOWDOWN = 4

/** Растянутый промежуток для таймера. */
export function slowMs(ms: number, бережём: boolean): number {
  return бережём ? Math.round(ms * SAVE_SLOWDOWN) : ms
}

// ── Состояние на всё приложение ──────────────────────────────────────────────
//
// Одно на всех: два места со своими копиями «бережём ли» разъедутся, и получится
// спектр, который считает, что бережём, при живом фоне, который считает иначе.

let сейчас: GameState = { gameRunning: false, visible: true, focused: true, enabled: true }
let бережём = false
const слушатели = new Set<(б: boolean) => void>()

/** Текущий ответ. */
export const isSaving = (): boolean => бережём

export function gameState(): Readonly<GameState> { return сейчас }

/** Сообщить об изменении обстановки. Возвращает true, если режим переключился. */
export function updateGameState(часть: Partial<GameState>): boolean {
  сейчас = { ...сейчас, ...часть }
  const надо = saving(сейчас)
  if (надо === бережём) return false
  бережём = надо
  слушатели.forEach(fn => { try { fn(бережём) } catch { /* сломанный слушатель не повод встать */ } })
  return true
}

/** Подписаться на переключение. Возвращает отписку. */
export function onSaving(fn: (б: boolean) => void): () => void {
  слушатели.add(fn)
  return () => { слушатели.delete(fn) }
}

/** Для проверок: вернуть всё в исходное. */
export function resetGameState() {
  сейчас = { gameRunning: false, visible: true, focused: true, enabled: true }
  бережём = false
  слушатели.clear()
}
