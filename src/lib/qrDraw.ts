/** Рисование QR. Библиотека грузится по требованию: на экране входа она нужна
 *  далеко не всем, а весит заметно. */
export async function drawQr(canvas: HTMLCanvasElement, текст: string) {
  const { default: qr } = await import('qrcode-generator')
  // Уровень коррекции M: код читается и с бликом на экране, но не раздувается.
  const т = qr(0, 'M')
  // Наше содержимое — только цифры и ЗАГЛАВНЫЕ буквы, поэтому «буквенно-цифровой»
  // режим: он вдвое плотнее побайтового, а значит квадратики крупнее.
  т.addData(текст, 'Alphanumeric')
  т.make()
  const n = т.getModuleCount()
  const поле = 4
  const пиксель = Math.max(2, Math.floor(240 / (n + поле * 2)))
  const сторона = (n + поле * 2) * пиксель
  canvas.width = сторона
  canvas.height = сторона
  const g = canvas.getContext('2d')
  if (!g) return
  // Белое поле вокруг обязательно: без него камера не находит границы кода.
  g.fillStyle = '#ffffff'
  g.fillRect(0, 0, сторона, сторона)
  g.fillStyle = '#000000'
  for (let r = 0; r < n; r++) {
    for (let c = 0; c < n; c++) {
      if (т.isDark(r, c)) g.fillRect((c + поле) * пиксель, (r + поле) * пиксель, пиксель, пиксель)
    }
  }
}
