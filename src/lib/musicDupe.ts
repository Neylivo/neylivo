export function isDuplicateTrack(e: { code?: string; message?: string } | null | undefined): boolean {
  if (!e) return false
  // 23505 — нарушение уникальности. Имя указателя проверяем тоже: на этой таблице
  // он один, и по нему видно, что дело именно в повторе трека.
  return e.code === '23505' || /duplicate key|music_tracks_url_uniq/i.test(e.message ?? '')
}
