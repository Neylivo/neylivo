// v1.557.0 (находка F1 аудита, шаги 2–3): вложения показываются по подписанной
// ссылке, а не по вечной публичной.
//
// ЧТО БЫЛО. Ссылка на вложение получалась через getPublicUrl и в таком виде
// ложилась в базу (messages.attach_url). У неё нет срока годности и нет
// проверки прав: кто угодно, узнав адрес, качает файл без всякого входа. Плюс
// сами бакеты были перечислимы анонимом — это закрыла миграция 110.
//
// ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ЗАКРЫТЬ БАКЕТ. Готовые публичные адреса зашиты в тысячах
// старых сообщений. Закрой бакет сегодня — вся история переписки осыпалась бы
// битыми картинками.
//
// ЧТО ЗДЕСЬ СДЕЛАНО. Показ идёт через createSignedUrl, а ПУТЬ объекта достаётся
// из самого публичного адреса. Значит:
//   • переносить записи в базе не нужно вовсе — ни одной строки не меняется;
//   • старые сообщения работают так же, как новые;
//   • когда бакет станет приватным, ничего не сломается — подписанная ссылка
//     работает и там, и там.
//
// ЧЕГО ЭТО НЕ ДЕЛАЕТ САМО ПО СЕБЕ. Пока бакет публичный, прямая ссылка
// по-прежнему отдаёт файл — то есть безопасность вырастет не сегодня, а в тот
// день, когда владелец выполнит последний шаг (supabase/111_storage_private.sql).
// Шаг отложен намеренно: пока у людей на руках старые версии приложения,
// закрытый бакет сломал бы им ВСЕ вложения. Сначала обновление расходится, потом
// закрывается бакет.
//
// ПОЧЕМУ ПАЧКОЙ. В ленте бывает полсотни картинок сразу. Подписывать каждую
// отдельным запросом — полсотни обращений к серверу на один экран; Supabase
// умеет createSignedUrls на список путей, и здесь всё, что попросили за один
// кадр, уезжает одним запросом.

/** Сколько живёт подписанная ссылка. Час — с запасом на долгое чтение ленты. */
export const СРОК = 60 * 60

/** Насколько раньше срока обновляем: ссылка не должна протухнуть на глазах. */
const ЗАПАС = 10 * 60 * 1000

const БАЗА = (import.meta.env.VITE_SUPABASE_URL as string) || ''

/** Бакеты, вложения которых мы подписываем. Аватары сюда не входят намеренно:
 *  они показываются десятками в каждом списке и меняются редко, а личного в
 *  пути к аватару нет — там только идентификатор владельца, который и так виден
 *  рядом. Это записано и в аудите. */
const НАШИ = ['attachments', 'modfiles']

export interface Объект { bucket: string; path: string }

/**
 * Разобрать публичный адрес хранилища на бакет и путь.
 *
 * Возвращает null для всего чужого: blob:, data:, картинки со сторонних сайтов,
 * адреса другого проекта Supabase. Такие адреса подписывать нечем, и трогать их
 * нельзя — иначе сломается показ всего, что лежит не у нас.
 */
export function разложить(url: string | null | undefined): Объект | null {
  if (!url) return null
  const s = String(url).trim()
  // Склейка нескольких вложений через \n (миграция v1.70.0) сюда попадать не
  // должна: разбирать её как один адрес значило бы подписать первый файл и
  // молча потерять остальные. Группу разбирает вызывающий, по одному.
  if (s.includes('\n')) return null
  if (!БАЗА || !s.startsWith(БАЗА)) return null
  // .../storage/v1/object/public/<бакет>/<путь>
  const m = s.match(/\/storage\/v1\/object\/(?:public\/)?([^/?#]+)\/(.+)$/)
  if (!m) return null
  const bucket = m[1]
  if (!НАШИ.includes(bucket)) return null
  // Хвосты вроде #enc и #spoiler к пути не относятся: это наши пометки, они
  // снимаются вызывающим. Запрос параметров у публичной ссылки не бывает, но
  // если появится — путь всё равно кончается до них.
  const path = decodeURIComponent(m[2].split(/[?#]/)[0])
  if (!path) return null
  return { bucket, path }
}

// ── Пачка ───────────────────────────────────────────────────────────────────

interface Запись { url: string; до: number }
const кэш = new Map<string, Запись>()          // "бакет/путь" -> подписанное

interface Ожидание { resolve: (u: string | null) => void }
const очередь = new Map<string, { bucket: string; path: string; ждут: Ожидание[] }>()
let таймер: ReturnType<typeof setTimeout> | null = null

async function отправитьПачку() {
  таймер = null
  const пачка = [...очередь.values()]
  очередь.clear()
  if (!пачка.length) return

  // По бакетам: createSignedUrls работает с одним бакетом за раз.
  const поБакетам = new Map<string, typeof пачка>()
  for (const з of пачка) {
    const л = поБакетам.get(з.bucket) ?? []
    л.push(з)
    поБакетам.set(з.bucket, л)
  }

  for (const [bucket, список] of поБакетам) {
    try {
      // Клиент подтягивается здесь, а не сверху файла, намеренно: разбор адреса
      // (разложить/публичный) должен проверяться в Node без единой строчки
      // Supabase, иначе проверка потащит за собой создание настоящего клиента.
      const { supabase } = await import('./supabase')
      const { data, error } = await supabase.storage.from(bucket)
        .createSignedUrls(список.map(з => з.path), СРОК)
      if (error || !data) throw error ?? new Error('пусто')
      const по = new Map<string, string>()
      for (const r of data) {
        // path в ответе — тот же, что просили; signedUrl относительный либо полный.
        if (r.signedUrl && r.path) по.set(r.path, полный(r.signedUrl))
      }
      for (const з of список) {
        const u = по.get(з.path) ?? null
        if (u) кэш.set(bucket + '/' + з.path, { url: u, до: Date.now() + СРОК * 1000 - ЗАПАС })
        for (const ж of з.ждут) ж.resolve(u)
      }
    } catch {
      // Подписать не вышло (нет сессии, сбой сети, файла нет). Отвечаем null —
      // вызывающий останется на прежнем адресе. Молчаливой поломки показа тут
      // быть не должно: пока бакет публичный, прежний адрес работает.
      for (const з of список) for (const ж of з.ждут) ж.resolve(null)
    }
  }
}

const полный = (u: string) => (/^https?:/i.test(u) ? u : БАЗА.replace(/\/$/, '') + '/storage/v1' + (u.startsWith('/') ? '' : '/') + u)

/**
 * Подписанная ссылка на вложение.
 *
 * Отдаёт исходный адрес, если это не наше хранилище или подписать не удалось, —
 * то есть хуже, чем было, не становится ни в одном случае.
 */
export async function подписать(url: string): Promise<string> {
  const о = разложить(url)
  if (!о) return url
  const ключ = о.bucket + '/' + о.path
  const был = кэш.get(ключ)
  if (был && был.до > Date.now()) return хвост(был.url, url)

  const готово = await new Promise<string | null>((resolve) => {
    const есть = очередь.get(ключ)
    if (есть) { есть.ждут.push({ resolve }); return }
    очередь.set(ключ, { bucket: о.bucket, path: о.path, ждут: [{ resolve }] })
    // Один кадр ожидания: за него в очередь успевает собраться вся видимая лента.
    if (!таймер) таймер = setTimeout(() => void отправитьПачку(), 16)
  })
  return готово ? хвост(готово, url) : url
}

/** Сохранить наши пометки (#spoiler, #enc) — они едут в самом адресе. */
function хвост(подписанный: string, исходный: string): string {
  const i = исходный.indexOf('#')
  return i >= 0 ? подписанный + исходный.slice(i) : подписанный
}

/**
 * Обратно к постоянному адресу — для «Скопировать ссылку».
 *
 * Подписанная ссылка живёт час. Человек, нажавший «скопировать ссылку», ждёт
 * ссылку, а не тыкву: он кладёт её в заметку, в другой чат, в задачу. Поэтому
 * копируется постоянный адрес объекта, а подпись остаётся делом показа.
 *
 * Когда бакет закроют, постоянный адрес перестанет отдавать файл постороннему —
 * и это ровно то, что задумано: ссылка останется рабочей для тех, кто вошёл, и
 * перестанет быть отмычкой для всех остальных.
 */
export function публичный(url: string): string {
  if (!БАЗА || !url.startsWith(БАЗА)) return url
  const m = url.match(/^(.*)\/storage\/v1\/object\/sign\/([^/?#]+)\/([^?#]+)(?:\?[^#]*)?(#.*)?$/)
  if (!m) return url
  return `${m[1]}/storage/v1/object/public/${m[2]}/${m[3]}${m[4] ?? ''}`
}

/** Для проверок: забыть всё подписанное. */
export function забыть(): void { кэш.clear(); очередь.clear(); if (таймер) { clearTimeout(таймер); таймер = null } }
