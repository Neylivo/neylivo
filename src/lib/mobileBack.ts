import { useEffect } from 'react'
import { IS_MOBILE } from './mobile'

// v1.427.0: кнопка «назад» на телефоне закрывает открытое, а не приложение.
//
// Что было. На Android системная кнопка «назад» — главный способ закрыть то, что
// открылось поверх. В нашем приложении она не делала ничего осмысленного: WebView
// отдавал её истории браузера, а истории у одностраничного приложения нет —
// значит, приложение просто закрывалось. Открыл Трекотеку, нажал «назад» — вышел
// из NeyLivo вместе с музыкой. Полноэкранное приложение без работающего «назад» на
// телефоне ощущается сломанным: это единственная кнопка, которая там есть всегда.
//
// Как сделано, и почему без плагинов. Capacitor отдаёт системную «назад» в
// историю WebView: есть куда возвращаться — возвращается, нет — закрывает
// приложение. Значит, достаточно на время открытого окна положить в историю одну
// запись. «Назад» снимает её, мы это ловим и закрываем окно сами. Нативный
// плагин не нужен, и он же не помог бы в браузере и в PWA, где то же самое делают
// кнопка «назад» браузера и жест «назад» на телефоне.
//
// Почему стек, а не по слушателю на каждое окно. Первая версия ставила свой
// popstate-обработчик каждой ловушке — и одно нажатие «назад» закрывало ВСЕ
// открытые окна разом: событие приходит всем слушателям. Это видно в стенде
// сразу (две ловушки — два закрытия), поэтому здесь один слушатель на всё
// приложение и стек: «назад» снимает только верхнее окно.

interface Trap { id: number; close: () => void }

let seq = 0
const stack: Trap[] = []
let listening = false

function onPop() {
  const top = stack.pop()
  if (!top) return
  top.close()
}

function listen() {
  if (listening) return
  listening = true
  window.addEventListener('popstate', onPop)
}

/**
 * Поставить ловушку: пока она стоит, системная «назад» вызовет close().
 * Возвращает функцию, которую надо позвать, если окно закрыли другим способом.
 */
export function pushBackTrap(close: () => void): () => void {
  const id = ++seq
  try { history.pushState({ ponoiTrap: id }, '') } catch { return () => {} }
  listen()
  const trap: Trap = { id, close }
  stack.push(trap)

  return () => {
    const at = stack.indexOf(trap)
    if (at < 0) return   // уже сняли самой «назад»
    stack.splice(at, 1)
    // Свою запись убираем, только если она всё ещё сверху: иначе шагнули бы
    // назад по чужой ловушке и закрыли не то окно.
    try {
      if ((history.state as any)?.ponoiTrap === id) history.back()
    } catch { /* истории нет — и не надо */ }
  }
}

/** Сколько окон сейчас держат «назад» — для проверок. */
export const backTrapDepth = (): number => stack.length

/**
 * То же для компонентов: пока open — «назад» закрывает.
 *
 * Только на телефоне: на компьютере «назад» браузера в приложении никто не жмёт,
 * а лишние записи в истории мешали бы вернуться на страницу, с которой пришли.
 */
export function useBackClose(open: boolean, close: () => void) {
  useEffect(() => {
    if (!open || !IS_MOBILE) return
    return pushBackTrap(close)
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open])
}
