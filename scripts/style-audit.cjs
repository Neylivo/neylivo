// Перепись вида: из скольких разных «кирпичей» сложено приложение.
// Запуск: npm run audit:ui
//
// Зачем. Владелец: «привести приложение к аккуратному минимализму, ничего не
// удаляя, а просто вместо сотен разных кнопок делать легче». Спорить об этом на
// глаз бессмысленно: «много» и «пёстро» — не числа. Здесь считается, сколько
// РАЗНЫХ значений одного и того же живёт в стилях.
//
// Почему с потолком. Один раз причесать можно и руками; беда в том, что на
// следующей же новой кнопке всё разъедется обратно, и никто этого не заметит.
// Потолок превращает перепись в проверку: добавил кнопку с новым фоном — она
// падает и называет виновника.
const fs = require('fs')
const path = require('path')

const CSS = [
  path.join(__dirname, '..', 'src', 'styles.css'),
  path.join(__dirname, '..', 'src', 'ponoi-ui.css'),
]

/** Разобрать css на пары «селектор → { свойство: значение }». Без библиотек:
 *  вложенных правил в этих файлах нет, кроме @media, а он нам не мешает. */
function правила(текст) {
  const без = текст.replace(/\/\*[\s\S]*?\*\//g, '')
  const из = []
  const re = /([^{}]+)\{([^{}]*)\}/g
  let m
  while ((m = re.exec(без))) {
    const сел = m[1].trim().replace(/\s+/g, ' ')
    if (!сел || сел.startsWith('@')) continue
    const свойства = {}
    for (const кусок of m[2].split(';')) {
      const i = кусок.indexOf(':')
      if (i < 0) continue
      свойства[кусок.slice(0, i).trim()] = кусок.slice(i + 1).trim()
    }
    из.push({ сел, свойства })
  }
  return из
}

/** Похоже ли, что селектор описывает кнопку. Нарочно широко: «modal-avbtn» и
 *  «pg-navbtn» — тоже кнопки, а по узкому правилу они выпадали из переписи, и
 *  первый заход их не причесал. */
const кнопочный = с => /button|btn|-act\b|-acts\b|-action/i.test(с)

/** Набор, к которому всё сведено. */
const ВЫСОТЫ = new Set(['28px', '32px', '40px', '44px', '48px'])
const ФОНЫ = new Set(['none', 'transparent', 'inherit', 'currentColor'])

// Что осталось за набором намеренно, с причиной. Это не «исключения, чтобы
// проверка молчала», а перечень мест, где своя мера обоснована.
const СВОИ = [
  [/\.composer/, 'поле ввода подогнано к своей пилюле по пикселям'],
  [/\.call-bar|\.c2-/, 'звонок: круглые кнопки поверх видео'],
  [/\.mus-ctl|\.mus2-ctl/, 'плеер: кнопка «играть» крупнее прочих намеренно'],
  [/img|\.emoji-btn|\.sset-/, 'это картинка внутри кнопки, а не сама кнопка'],
  [/\.cset-tri|\.att-edit-btn|\.c2-share-ctl/, 'крошечные значки поверх содержимого'],
  [/\.ic-btn/, 'крупная плитка выбора, не кнопка в ряду'],
  [/\.dm-findbtn|\.srv-pill/, 'это поле поиска, а не кнопка: оно намеренно темнее панели'],
  [/gradient|#fff|#e3e3e3|var\(--green\)|var\(--mus-a|!important/, 'свой цвет по смыслу'],
]
const своё = с => СВОИ.find(([re]) => re.test(с))

const все = []
for (const f of CSS) if (fs.existsSync(f)) все.push(...правила(fs.readFileSync(f, 'utf8')))
const кнопки = все.filter(п => кнопочный(п.сел))

let провал = 0
const проверка = (имя, сколько, потолок, список) => {
  const ок = сколько <= потолок
  console.log((ок ? '  ok   ' : '  ПРОВАЛ ') + имя + ': ' + сколько + ' (потолок ' + потолок + ')')
  if (список && список.length) console.log('         ' + список.slice(0, 8).join('; '))
  if (!ок) провал++
}

console.log('── Перепись вида ──')
console.log('правил про кнопки : ' + кнопки.length)
console.log('разных имён кнопок: ' + new Set(
  кнопки.map(п => п.сел.split(/[\s,:>]/)[0]).filter(с => с.startsWith('.'))).size)

// 1. Высоты вне набора.
const чужиеВысоты = []
for (const п of кнопки) {
  for (const свойство of ['height', 'min-height']) {
    const v = п.свойства[свойство]
    if (!v || !/^[\d.]+px$/.test(v) || ВЫСОТЫ.has(v)) continue
    if (своё(п.сел)) continue
    чужиеВысоты.push(п.сел.slice(0, 40) + ' → ' + v)
  }
}

// 2. Фоны вне набора.
const чужиеФоны = []
for (const п of кнопки) {
  const v = (п.свойства['background'] || п.свойства['background-color'] || '').trim()
  if (!v || ФОНЫ.has(v) || v.startsWith('var(--btn-')) continue
  if (своё(п.сел) || своё(v)) continue
  чужиеФоны.push(п.сел.slice(0, 40) + ' → ' + v.slice(0, 34))
}

console.log('')
проверка('высот кнопок вне набора {28,32,40,44,48}', чужиеВысоты.length, 0, чужиеВысоты)
проверка('фонов кнопок вне набора --btn-*', чужиеФоны.length, 0, чужиеФоны)

// 3. Неровности темы: цвет вписан жёстко там, где решать должна тема.
//
// Владелец: «все неровности в теме приложения починить». Беда невидима из
// тёмной темы: #dbdee1 и var(--tx) там ОДИН И ТОТ ЖЕ цвет. Светлая тема меняет
// переменную, а вписанное число — нет, и остаётся светло-серая надпись на белом.
// Обход (npm run test:contrast) ловит это на тринадцати экранах; здесь ловится
// везде, включая то, до чего обход не доходит.
const ПАЛИТРА_ТЕКСТА = {
  '#f2f3f5': '--tx-1', '#dbdee1': '--tx', '#b5bac1': '--tx-2',
  '#949ba4': '--mut', '#80848e': '--mut',
}
const жёсткийТекст = []
for (const п of все) {
  const v = (п.свойства['color'] || '').trim().toLowerCase()
  const имя = ПАЛИТРА_ТЕКСТА[v]
  if (имя) жёсткийТекст.push(п.сел.slice(0, 40) + ' → ' + v + ' (это var(' + имя + '))')
}

// Белый текст на подложке, которая сама зависит от темы: на светлой это белым
// по светлому. Белый на бренде, красном или фотографии — совсем другое дело, и
// сюда не попадает.
const белыйНаТеме = []
for (const п of все) {
  const c = (п.свойства['color'] || '').trim()
  if (!/^#fff(fff)?$|^white$/i.test(c)) continue
  const b = (п.свойства['background'] || п.свойства['background-color'] || '')
  if (/var\(--(bg|c-(dark|main|panel|content|hover|active))|rgba\(var\(--ov|var\(--btn-(soft|tint)/.test(b)) {
    белыйНаТеме.push(п.сел.slice(0, 40) + ' на ' + b.slice(0, 30))
  }
}

console.log('')
проверка('жёстких цветов текста из палитры', жёсткийТекст.length, 0, жёсткийТекст)
проверка('белого текста на подложке темы', белыйНаТеме.length, 0, белыйНаТеме)

// 3. Общая пестрота: сколько разных размеров текста и скруглений во всём файле.
const разных = (свойство, годен = () => true) => {
  const набор = new Set()
  for (const п of все) {
    const v = п.свойства[свойство]
    if (!v) continue
    for (const з of v.split(/\s+/)) if (/^-?[\d.]+px$/.test(з) && годен(з)) набор.add(з)
  }
  return набор
}
const шрифты = разных('font-size')
const скругления = разных('border-radius')
проверка('разных размеров текста', шрифты.size, 24, [...шрифты].sort((a, b) => parseFloat(a) - parseFloat(b)))
проверка('разных скруглений в пикселях', скругления.size, 21, [...скругления].sort((a, b) => parseFloat(a) - parseFloat(b)))

// 5. События без слушателей — кнопки, которые не делают ничего.
//
// Владелец знает этот вид поломки лучше всех: «настройка есть» ещё не значит
// «работает». Кнопка шлёт событие, слушателя нет, нажатие проваливается в
// пустоту — и человек решает, что сломано приложение. На этом я попался в
// v1.546.0: два раздела в мобильной рейке не делали ровно ничего.
const шлют = new Map(), слушают = new Set()
const идтиПоИсходникам = д => {
  for (const ф of fs.readdirSync(д)) {
    const п = path.join(д, ф)
    if (fs.statSync(п).isDirectory()) { идтиПоИсходникам(п); continue }
    if (!/\.(ts|tsx)$/.test(ф)) continue
    const т = fs.readFileSync(п, 'utf8')
    for (const m of т.matchAll(/CustomEvent\(\s*'(ponoi-[\w-]+)'/g)) {
      if (!шлют.has(m[1])) шлют.set(m[1], п)
    }
    // Слушать можно тремя способами: окном, снятием всех слушателей перед
    // подпиской и мостом настольной части. Считаем все три.
    for (const m of т.matchAll(/addEventListener\(\s*'(ponoi-[\w-]+)'/g)) слушают.add(m[1])
    for (const m of т.matchAll(/removeAllListeners\(\s*'(ponoi-[\w-]+)'/g)) слушают.add(m[1])
    for (const m of т.matchAll(/\bon\(\s*'(ponoi-[\w-]+)'/g)) слушают.add(m[1])
  }
}
идтиПоИсходникам(path.join(__dirname, '..', 'src'))
const глухие = [...шлют.entries()]
  .filter(([имя]) => !слушают.has(имя))
  .map(([имя, где]) => имя + ' (' + path.basename(где) + ')')

console.log('')
проверка('событий без единого слушателя', глухие.length, 0, глухие)

console.log('\nИТОГ: провалено ' + провал)
process.exit(провал ? 1 : 0)
