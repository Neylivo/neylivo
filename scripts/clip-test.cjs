// v1.538.0: запись последних секунд экрана правда пишется. Запуск: npm run test:clip
//
// Владелец: «добавить возможность как в Medal сохранять от 5 секунд до 3 минут
// того, что происходило на экране».
//
// Проверяется НАСТОЯЩИЙ путь: захват экрана, кольцо кусков, сохранение файла на
// диск и то, что этот файл открывается и декодируется. Половинчатая проверка
// («функция вызвалась») тут ничего не стоила бы: главная беда этой затеи —
// файл, который весит мегабайты и не открывается ничем, потому что у webm
// первый кусок это заголовок, и выбрасывать его нельзя.
const { app, BrowserWindow, session, desktopCapturer } = require('electron')
const fs = require('fs')
const path = require('path')
const клипы = require('./../electron/clipRecorder.cjs')

const OUT = path.join(__dirname, '..', 'dist-clip-test')
fs.mkdirSync(OUT, { recursive: true })
// Начинаем с ПУСТОЙ папки.
//
// 12.08.2026 проверка упала на «список видит все сохранённые клипы — нашлось 4»
// при исправном коде: в папке лежали клипы от прошлых прогонов, и список честно
// вернул их все. Проверка, падающая от собственного мусора, хуже, чем никакой:
// на неё перестают смотреть. Удаляем только клипы и только в своей папке.
for (const f of fs.readdirSync(OUT)) {
  if (f.endsWith('.webm')) { try { fs.unlinkSync(path.join(OUT, f)) } catch { /* занят — переживём */ } }
}

let failed = 0
const check = (name, ok, extra) => {
  console.log((ok ? '  ok   ' : '  ПРОВАЛ ') + name + (extra ? '  — ' + extra : ''))
  if (!ok) failed++
}

app.disableHardwareAcceleration()
setTimeout(() => { console.log('ЗАВИС'); process.exit(2) }, 120000)

app.whenReady().then(async () => {
  session.defaultSession.setDisplayMediaRequestHandler((request, cb) => {
    desktopCapturer.getSources({ types: ['screen'] }).then(s => cb({ video: s[0] }))
  })

  console.log('\n── Запись последних секунд экрана ──')

  // Качество нарочно высокое: на клипе в мегабайт разница между «файл пишет
  // окно записи» и «клип едет массивом чисел через границу процессов» тонет в
  // шуме. Я на этом попался — слом прошёл незамеченным. При восьми мегабитах
  // за те же восемь секунд набирается около восьми мегабайт, и старый путь
  // сразу видно по приросту памяти.
  const пуск = await клипы.start({ seconds: 10, fps: 30, height: 720, bitrate: 8_000_000, folder: OUT })
  check('запись началась', пуск.ok === true, пуск.why || '')
  if (!пуск.ok) { console.log('\nИТОГ: провалено ' + (failed + 1)); process.exit(1) }

  // Ждём дольше, чем длина клипа: так проверяется и вытеснение старых кусков.
  await new Promise(r => setTimeout(r, 8000))

  const рано = клипы.state()
  check('запись идёт и знает свою папку', рано.running === true && !!рано.folder, рано.folder)

  const итог = await клипы.save(5, 'проверка.webm')
  check('клип сохранён на диск', итог.ok === true, итог.why || итог.path || '')
  if (итог.ok) {
    const размер = fs.statSync(итог.path).size
    check('файл не пустой', размер > 20000, Math.round(размер / 1024) + ' КБ')

    // Главное: файл ОТКРЫВАЕТСЯ. Проверяем движком, а не по расширению.
    //
    // Окно нарочно обычное: file://-страница и защита включена — ровно как в
    // приложении, где клип показывается прямо в настройках. С webSecurity:false
    // проверка проходила бы и в том случае, когда у настоящего окна доступа к
    // файлу нет и человек видит чёрный прямоугольник.
    // Страница нарочно лежит в ДРУГОЙ папке, чем клип: в приложении окно живёт
    // внутри программы, а клипы — в «Видео/NeyLivo», и проверять надо именно
    // чтение из чужой папки.
    const стенд = path.join(require('os').tmpdir(), 'ponoi-clip-player.html')
    fs.writeFileSync(стенд, '<meta charset=utf-8><body></body>', 'utf8')
    const win = new BrowserWindow({ show: false, width: 400, height: 300,
      webPreferences: { backgroundThrottling: false } })
    await win.loadFile(стенд)

    // Открывает файл движком и возвращает, что тот про него понял.
    //
    // Ошибка движка называется КОДОМ, а не просто «не открылось»: 11.08.2026 эта
    // проверка упала один раз на двадцать один, и по записи «0x0, готовность -1»
    // нельзя было сказать ничего — битый ли клип, отказ ли декодера. Дороже всего
    // в такой проверке не падение, а падение, из которого ничего не следует.
    const открыть = async файл => JSON.parse(await win.webContents.executeJavaScript(`(async () => {
      const v = document.createElement('video')
      v.muted = true
      document.body.appendChild(v)
      v.src = ${JSON.stringify('file:///' + 'ЗАМЕНА')}
      v.load()
      const r = await new Promise(готово => {
        const глянуть = () => готово({ w: v.videoWidth, h: v.videoHeight, s: v.readyState, e: null })
        v.onloadeddata = глянуть
        v.onerror = () => готово({ w: 0, h: 0, s: -1,
          e: (v.error ? v.error.code + ': ' + v.error.message : 'без v.error') })
        setTimeout(глянуть, 6000)
      })
      v.remove()
      return JSON.stringify(r)
    })()`.replace('ЗАМЕНА', файл.replace(/\\/g, '/'))))

    // Вторая попытка — только после ошибки движка и только один раз.
    //
    // Битый файл не открывается НИКОГДА, поэтому повтор его не спасает: ниже это
    // доказано сломом, и слом идёт через ЭТУ ЖЕ функцию, а не мимо неё.
    // А одиночная осечка декодера повтор переживает, и от неё проверка больше не
    // врёт про поломку, которой нет.
    const открытьДважды = async файл => {
      const раз = await открыть(файл)
      if (раз.s !== -1) return раз
      const два = await открыть(файл)
      два.e = 'с первого раза: ' + раз.e + (два.s === -1 ? '; со второго: ' + два.e : '; со второго открылся')
      return два
    }

    const кадр = await открытьДважды(итог.path)
    check('клип открывается и декодируется', кадр.w > 0 && кадр.h > 0,
      кадр.w + 'x' + кадр.h + ', готовность ' + кадр.s + (кадр.e ? ', ' + кадр.e : ''))

    // Слом на месте: проверка обязана уметь падать.
    //
    // У webm первый кусок — описание дорожек, и ровно его потеря даёт файл на
    // мегабайты, который не открывается ничем. Берём тот же клип без начала: если
    // движок примет и его, то верхняя проверка ничего не стоит.
    const обрезок = path.join(OUT, 'без-начала.webm')
    fs.writeFileSync(обрезок, fs.readFileSync(итог.path).slice(4096))
    const битый = await открытьДважды(обрезок)
    check('проверка умеет падать: клип без начала не открывается',
      !(битый.w > 0 && битый.h > 0),
      битый.w + 'x' + битый.h + ', готовность ' + битый.s + (битый.e ? ', ' + битый.e : ''))
    try { fs.unlinkSync(обрезок) } catch { /* уже нет */ }
  }

  // v1.541.0: сохранение не должно стоить памяти.
  //
  // Владелец: «при сохранении клипа приложение просто ломается». Так и было:
  // клип ехал из окна записи в главный процесс ОБЫЧНЫМ МАССИВОМ ЧИСЕЛ
  // (Array.from). Тринадцать мегабайт видео — это тринадцать миллионов
  // элементов и полтораста мегабайт памяти сверху; три минуты в качестве
  // «Чётко» — это уже двести мегабайт видео, и V8 просто отказывается:
  // «Invalid array length», клип потерян. Воспроизведено полностью.
  //
  // Проверяем не «упало/не упало», а ЦЕНУ: сколько памяти прибавилось у
  // главного процесса за сохранение. Ждать три минуты ради падения в проверке
  // нельзя, а цена видна сразу и на маленьком клипе: у старого пути она
  // примерно вдесятеро больше самого клипа, у нового — около нуля, потому что
  // через границу процессов едет только строка с путём.
  const доПамяти = process.memoryUsage().rss
  const тяж = await клипы.save(8, 'память.webm')
  const послеПамяти = process.memoryUsage().rss
  const приросло = Math.round((послеПамяти - доПамяти) / 1048576)
  const весит = тяж.ok ? Math.round(тяж.bytes / 1048576) : 0
  check('клип сохранён', тяж.ok === true, тяж.why || '')
  check('сохранение не тащит клип через границу процессов',
    приросло < 25, 'прибавилось ' + приросло + ' МБ при клипе ' + весит + ' МБ')

  // Прирост памяти — мера честная, но на стенде ненадёжная: экран во время
  // проверки почти неподвижен, и клип сжимается до мегабайта, на котором
  // разница тонет в шуме. Я это проверил сломом — старый путь прошёл незаметно.
  //
  // Поэтому главное утверждение здесь другое и от размера не зависит: в ответе
  // окна записи НЕ ДОЛЖНО быть байтов. Ни массивом, ни типизированным массивом,
  // ни как угодно ещё — только путь и число. Правило названо по существу, а не
  // по имени поля: новое поле с байтами поймается тоже.
  const тяжёлые = Object.entries(тяж)
    .filter(([, v]) => Array.isArray(v) || ArrayBuffer.isView(v) || v instanceof ArrayBuffer)
    .map(([k, v]) => k + ' (' + (Array.isArray(v) ? v.length : v.byteLength) + ')')
  check('в ответе окна записи нет самих байтов клипа',
    тяжёлые.length === 0, тяжёлые.join(', ') || Object.keys(тяж).join(','))

  // v1.539.0: список клипов и то, чем он открывается.
  //
  // Список читается из папки, а не из памяти: только так проверяется, что там
  // лежит настоящий файл и что удаление правда его убирает.
  const второй = await клипы.save(5, клипы.имяКлипа(new Date(), 'Half-Life 2'))
  check('второй клип сохранён', второй.ok === true, второй.why || '')
  const список = клипы.list()
  // Считаем не «сколько всего», а «сколько сохранили»: проверок сохранения тут
  // несколько, и жёсткое число ломалось бы от каждой новой.
  //
  // Именно этим комментарий и оправдывался, пока рядом стояло жёсткое «=== 3».
  // Считаем по-настоящему: сколько раз сохранили выше — столько и должно
  // лежать. Так проверка переживёт и новую проверку сохранения, и чужой файл в
  // папке, если чистка вдруг не сработает.
  const сохранили = ['проверка.webm', 'память.webm', второй.path].filter(Boolean).length
  check('список видит все сохранённые клипы', список.length === сохранили,
    'нашлось ' + список.length + ', сохраняли ' + сохранили)
  check('в списке есть размер и время', список.every(c => c.bytes > 0 && c.at > 0))
  check('новый клип идёт первым', список[0].at >= список[1].at)
  // Дефис и пробел в названии игры остаются: это не запретные для файла знаки.
  check('название игры попало в имя целиком', /^Half-Life 2 /.test(список[0].name), список[0].name)

  // Имя должно зависеть от МОМЕНТА нажатия: раньше окно присылало готовое имя
  // вместе с настройками, и второе нажатие F7 писало файл поверх первого.
  const а = клипы.имяКлипа(new Date(2026, 7, 5, 12, 0, 0), null)
  const б = клипы.имяКлипа(new Date(2026, 7, 5, 12, 0, 1), null)
  check('два нажатия подряд дают разные имена', а !== б, а + ' / ' + б)
  // Имя собирается в двух местах: здесь (для F7) и в src/lib/clipBuffer.ts (для
  // кнопки). Обе проверки сверяются с одной и той же строкой — иначе клипы от
  // клавиши и от кнопки начнут называться по-разному, и никто этого не заметит.
  const образец = клипы.имяКлипа(new Date(2026, 7, 5, 12, 0, 0), 'Half-Life 2')
  check('формат имени тот же, что у кнопки', образец === 'Half-Life 2 2026-08-05 12-00-00.webm', образец)
  check('в имени нет запрещённых для Windows знаков', !/[\\/:*?"<>|]/.test(клипы.имяКлипа(new Date(), 'A/B:C*D')))

  // Путь горячей клавиши целиком: настройки от окна + два нажатия подряд.
  //
  // Именно здесь была ошибка, которую видно только по файлам: окно присылало
  // готовое имя вместе с настройками, и ВТОРОЕ нажатие писало поверх первого
  // клипа. Проверка нажимает дважды в одну секунду — самый злой случай.
  клипы.hotkeySettings({ seconds: 5, game: 'Portal 2' })
  const было = клипы.list().length
  const н1 = await клипы.saveHotkey()
  const н2 = await клипы.saveHotkey()
  check('клавиша сохраняет клип', н1.ok === true && н2.ok === true, (н1.why || '') + (н2.why || ''))
  check('второе нажатие не затирает первое', н1.path !== н2.path, (н1.path || '') + ' / ' + (н2.path || ''))
  check('оба файла лежат на диске', клипы.list().length === было + 2, 'стало ' + клипы.list().length)
  check('клавиша берёт длину и игру из настроек', /^Portal 2 /.test(path.basename(н1.path || '')), path.basename(н1.path || ''))
  for (const p of [н1.path, н2.path]) { try { fs.unlinkSync(p) } catch { /* уже нет */ } }

  const мимо = клипы.remove('../../важное.webm')
  check('удаление не выходит из папки клипов', мимо.ok === false, мимо.why || '')
  const доУдаления = клипы.list().length
  const убрали = клипы.remove(список[0].name)
  check('клип удаляется', убрали.ok === true, убрали.why || '')
  const после = клипы.list()
  check('удалённого нет в списке',
    после.length === доУдаления - 1 && !после.some(c => c.name === список[0].name),
    'было ' + доУдаления + ', стало ' + после.length)

  клипы.stop()
  check('запись останавливается', клипы.state().running === false)

  // Прибираем за собой: проверка не должна оставлять мусор в репозитории.
  try { for (const f of fs.readdirSync(OUT)) fs.unlinkSync(path.join(OUT, f)) } catch { /* уже чисто */ }

  console.log('\nИТОГ: провалено ' + failed)
  process.exit(failed ? 1 : 0)
})
