// v1.557.0 (находка F5 аудита): окну запрещено уходить на чужой адрес.
//
// ЧТО БЫЛО. `setWindowOpenHandler` в main.cjs есть — открыть НОВОЕ окно на http
// нельзя, ссылка уходит в системный браузер. А обработчика `will-navigate` не
// было вовсе: если что-то внутри страницы уводило сам документ (window.location,
// форма с action, метаобновление, ссылка с target=_self), чужая страница
// открывалась прямо в окне приложения — там, где рядом живёт preload.cjs со
// своими каналами в главный процесс. То есть чужой странице доставался мост.
//
// ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ. Правило, написанное внутри createWindow, однажды
// забудут для второго окна (их тут пять: главное, накладка звонка, всплывашка
// игры, сплэш, запись клипа). Здесь оно вешается на `web-contents-created`, то
// есть на всё, что вообще появится. И заодно эту логику можно проверить
// настоящей пробой — scripts/nav-test.cjs.

/**
 * Свой ли адрес.
 *
 * file://      — собранное приложение;
 * localhost    — режим разработки (vite на 5173);
 * data:/about:/blob: — служебные окна накладки, всплывашки и сплэша грузят себя
 *                именно так, а about:srcdoc — это рамки плагинов.
 */
function своё(url) {
  try {
    const u = new URL(String(url))
    if (u.protocol === 'file:' || u.protocol === 'data:' || u.protocol === 'about:' || u.protocol === 'blob:') return true
    if ((u.protocol === 'http:' || u.protocol === 'https:') && (u.hostname === 'localhost' || u.hostname === '127.0.0.1')) return true
    return false
  } catch { return false }
}

/**
 * Повесить сторожа на все веб-содержимые приложения.
 *
 * @param {import('electron').App} app
 * @param {(url: string) => any} наружу  чем открыть чужую ссылку (shell.openExternal)
 */
function поставитьСторожа(app, наружу) {
  app.on('web-contents-created', (_e, contents) => сторожить(contents, наружу))
}

/** То же для одного окна — этим пользуется проба. */
function сторожить(contents, наружу) {
  // В Electron 31 у этих событий новая форма (один объект со свойством url) и
  // старая (url вторым доводом) одновременно — берём то, что пришло.
  const адрес = (e, url) => String(url || (e && e.url) || '')
  const держать = (e, url) => {
    const u = адрес(e, url)
    if (своё(u)) return
    e.preventDefault()
    // Ссылку не съедаем: человек нажал её осознанно, пусть откроется снаружи.
    //
    // Отдаём наружу не только http(s), а всё чужое. Иначе я бы сломал диплинки:
    // openGameLink (src/lib/gameShare.ts) при отсутствии моста ставит
    // window.location = 'roblox://…', и до этой правки такой переход уходил
    // обработчику протокола в системе. Запрет без openExternal превратил бы
    // «Поделиться игрой» в кнопку, которая не делает ничего.
    if (u) { try { наружу(u) } catch {} }
  }

  contents.on('will-navigate', держать)

  // Перенаправление уже начатой навигации (301/302 на чужой адрес) обходит
  // will-navigate, поэтому проверяем и его.
  contents.on('will-redirect', (e, url) => {
    if (e && e.isMainFrame === false) return
    держать(e, url)
  })

  // ВЛОЖЕННЫЕ РАМКИ СЮДА НЕ ВХОДЯТ, И ЭТО НЕ НЕДОСМОТР.
  //
  // Есть событие will-frame-navigate — оно ловит переходы в любой рамке. Я его
  // сначала повесил и снял: оно срабатывает и на ПЕРВУЮ загрузку рамки по её
  // src. То есть запрет чужих адресов убил бы встроенный проигрыватель YouTube
  // в музыке и любую страницу плагина, которая грузится не из srcdoc, —
  // приложение сломалось бы там, где никакой дыры нет.
  //
  // Защищать надо главную рамку: preload.cjs с каналами в главный процесс живёт
  // только в ней. У вложенных его нет вовсе, а рамки плагинов вдобавок стоят в
  // sandbox без allow-same-origin — чужое происхождение без доступа к
  // приложению (см. src/lib/plugins/htmlFrame.ts).

  // <webview> в приложении не используется ни разу. Раз так — пусть его нельзя
  // будет добавить и случайно: тег живёт по своим правилам безопасности.
  contents.on('will-attach-webview', (e) => e.preventDefault())
}

module.exports = { своё, поставитьСторожа, сторожить }
